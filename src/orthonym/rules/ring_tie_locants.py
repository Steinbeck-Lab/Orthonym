"""The parent of two heteroaromatic monocycles that tie on every criterion of: the ring whose
prefixes take the lower locants,.

 (the Blue Book): "These prefixes are assigned the lowest locants available after priority has
been given to the principal characteristic groups and the linking multiplicative substituent groups. Such names
are not acceptable as preferred IUPAC names... preferred IUPAC names are generated by substitutive nomenclature
principles", with its example '2-chloro-4-[(5-chloropyridin-2-yl)oxy]pyridine (PIN) [not 5-chloro-2-[(2-chloro
pyridin-4-yl)oxy]pyridine; the locant set for the substituents '2,4' in the PIN is lower than '2,5'; see ]'
(:6267). (:21600): "The preferred IUPAC name is based on the senior parent structure that has the maximum
number of substituents cited as prefixes", (:21698): "... the senior parent structure that has the lower
locant or set of locants for substituents cited as prefixes".

Scope, by construction: the rings that tie are the only ring systems of the molecule, they are monocycles of the
same aromatic skeleton with a ring heteroatom (a benzene ring has its own selector,
``benzene._preferred_benzene_parent_ring``), and every atom outside them is a halogen, a carbon or a divalent
oxygen or sulfur joined by single bonds with no hydrogen on the oxygen or sulfur: a molecule with no principal
characteristic group and no multiple bond outside the rings, so has nothing to decide and the prefixes are
the whole story. The ring numbering is the heteroatom cascade of ``heterocycles._monocycle_numberings``,
:8284), before any locant of a prefix. A tie that stays a tie (equal counts and equal locant sets) is left to the
caller, as before.
"""
from __future__ import annotations

from typing import List, Optional, Set

_HALOGENS = frozenset({9, 17, 35, 53})


def _plain_outside(mol, ring_atoms: Set[int]) -> bool:
    """True when every atom outside ``ring_atoms`` is a halogen, a carbon (none in a ring) or an O or S with two
    heavy neighbours and no hydrogen, and every bond to or between them is single."""
    for atom in mol.GetAtoms():
        idx = atom.GetIdx()
        if idx in ring_atoms:
            continue
        if atom.IsInRing() or atom.GetFormalCharge() != 0 or atom.GetNumRadicalElectrons() != 0:
            return False
        z = atom.GetAtomicNum()
        if z in _HALOGENS or z == 6:
            pass
        elif z in (8, 16):
            if atom.GetDegree() != 2 or atom.GetTotalNumHs() != 0:
                return False
        else:
            return False
        if any(b.GetBondTypeAsDouble() != 1.0 for b in atom.GetBonds()):
            return False
    return True


def _cycle(mol, system: Set[int]) -> Optional[List[int]]:
    """The atoms of the monocycle ``system`` in ring order, or None when it is not one aromatic ring with a
    heteroatom."""
    inside = [r for r in mol.GetRingInfo().AtomRings() if set(r) <= system]
    if len(inside) != 1 or set(inside[0]) != system or len(system) > 10:
        return None
    ring = list(inside[0])
    if not all(mol.GetAtomWithIdx(a).GetIsAromatic() for a in ring):
        return None
    if all(mol.GetAtomWithIdx(a).GetAtomicNum() == 6 for a in ring):
        return None
    return ring


def _skeleton(mol, ring: List[int]) -> tuple:
    """The element sequence of a ring as the least of its rotations and reflections."""
    seq = [mol.GetAtomWithIdx(a).GetAtomicNum() for a in ring]
    n = len(seq)
    return min(tuple(s[(i + k) % n] for k in range(n))
               for s in (seq, seq[::-1]) for i in range(n))


def _locant_key(mol, ring: List[int]) -> tuple:
    """``(-number of prefixes, lowest locant set)`` of the ring as the parent, under the numberings its
    heteroatoms allow,."""
    from .heterocycles import _monocycle_numberings
    members = set(ring)
    exo = {pos: sum(1 for nb in mol.GetAtomWithIdx(a).GetNeighbors() if nb.GetIdx() not in members)
           for pos, a in enumerate(ring)}
    numberings = _monocycle_numberings(mol, ring)
    best_het = min(het for het, _loc in numberings)
    sets = [tuple(sorted(loc[pos] for pos, n in exo.items() for _ in range(n)))
            for het, loc in numberings if het == best_het]
    return (-sum(exo.values()), min(sets))


def senior_by_prefix_locants(mol, ring_systems, tied) -> Optional[int]:
    """The index (of ``ring_systems``) of the tied ring that is the parent by and, else None."""
    if len(ring_systems) != len(tied):
        return None
    atoms: Set[int] = set()
    cycles = []
    for i in tied:
        ring = _cycle(mol, set(ring_systems[i]))
        if ring is None:
            return None
        cycles.append(ring)
        atoms |= set(ring)
    if len({_skeleton(mol, ring) for ring in cycles}) != 1 or not _plain_outside(mol, atoms):
        return None
    keys = [_locant_key(mol, ring) for ring in cycles]
    best = min(keys)
    if keys.count(best) != 1:
        return None
    return tied[keys.index(best)]
