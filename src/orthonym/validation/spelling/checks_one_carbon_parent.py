"""Spelling check of the locant '1' on a one-carbon amine parent; registered with
:func:`orthonym.validation.pin_spelling.register`).

 (the Blue Book, under " Omission of locants"): "Locants are omitted when no
isomer can be generated by moving suffixes and/or prefixes (if any) from their position to another or
by interchanging them between two different positions." The parent 'methanamine' has two positions, the
carbon and the nitrogen of the suffix, so the locant '1' of a group on the carbon is cited exactly when
a group can be moved between them:

* the nitrogen holds a hydrogen, so a group of the carbon could stand on it:
  '1-hydrazinylmethanamine (PIN)' (:38535), '1-chloromethanaminium';
* the carbon holds a hydrogen and a group of the nitrogen that keeps the parent (a ring atom or a
  heteroatom; an acyclic carbon would lengthen the chain) could stand on it: 'N,1-bis(4-chlorophenyl)
  methanimine (PIN)' (:26524), '(1E)-1-[...]-N-[...]methanimine (PIN)' (:50452);
* otherwise no isomer exists and the locant is omitted: 'cyano-N,N-dimethylmethanamine N-oxide (PIN)'
   "aci-Nitro compounds",:36580), '(Z)-N-hydroxy(4-chlorophenyl)(phenyl)methanimine (PIN)'
  (:47666).

A protonated tertiary amine holds a hydrogen the neutral amine does not, so '1-methoxy-N,N-dimethyl-
methanaminium' cites the locant where 'methoxy-N,N-dimethylmethanamine' omits it. The check reads the
structure and the name text only, and decides only when the name and the structure agree on one parent;
it abstains otherwise.
"""
from __future__ import annotations

import re
from typing import List, Optional, Tuple

from ..pin_spelling import SpellingFailure, register
from .units import parse_name

_PARENT = re.compile(r"methan(?:amin|imin)(?:e|ium)")


def _candidates(mol) -> List[Tuple[int, int]]:
    """(carbon, nitrogen) pairs of a one-carbon chain bonded to an acyclic nitrogen of an amine,
    imine or their cations: the carbon is in no ring and has no acyclic carbon neighbour (that
    carbon would lengthen the chain), the nitrogen is in no ring and not aromatic, and the carbon
    holds no oxo group (an amide)."""
    out = []
    for c in mol.GetAtoms():
        if c.GetSymbol() != "C" or c.IsInRing():
            continue
        if any(n.GetSymbol() == "C" and not n.IsInRing() for n in c.GetNeighbors()):
            continue
        if any(b.GetBondTypeAsDouble() == 2 and b.GetOtherAtom(c).GetSymbol() == "O"
               for b in c.GetBonds()):
            continue
        for n in c.GetNeighbors():
            if n.GetSymbol() == "N" and not n.IsInRing() and not n.GetIsAromatic():
                out.append((c.GetIdx(), n.GetIdx()))
    return out


def _carbon_groups(mol, c_idx: int, n_idx: int) -> int:
    """The number of groups the carbon carries apart from the nitrogen."""
    return sum(1 for x in mol.GetAtomWithIdx(c_idx).GetNeighbors()
               if x.GetIdx() != n_idx and x.GetAtomicNum() > 1)


def _locant_required(mol, c_idx: int, n_idx: int) -> bool:
    """ for the carbon and the nitrogen of the parent."""
    c = mol.GetAtomWithIdx(c_idx)
    n = mol.GetAtomWithIdx(n_idx)
    if n.GetTotalNumHs() > 0:
        return True
    if c.GetTotalNumHs() == 0:
        return False
    for x in n.GetNeighbors():
        if x.GetIdx() == c_idx or x.GetAtomicNum() <= 1 or x.GetFormalCharge() != 0:
            continue
        if x.GetSymbol() == "C" and not x.IsInRing():
            continue
        return True
    return False


@register("P-14.3.4.4")
def one_carbon_amine_locant_check(mol, name) -> Optional[SpellingFailure]:
    """The locant '1' of a group on the carbon of 'methanamine', 'methanaminium', 'methanimine' or
    'methaniminium' is cited exactly when requires it (see the module text)."""
    try:
        _s, _encs, ps = parse_name(name)
    except Exception:  # noqa: BLE001 -- a name the reader cannot read is not decided here
        return None
    units = [p for p in ps if p.unit.encl is None and _PARENT.fullmatch(p.parent or "")]
    if len(units) != 1 or {"multiplicative", "isotope_or_other"} & set(units[0].notes):
        return None
    unit = units[0]
    # the groups cited on the carbon: a prefix locant that is not an element locant, or none at all
    c_groups = 0
    cites_one = False
    for pr in unit.prefixes:
        numeric = [loc for loc in pr.locs if not loc[:1].isalpha()]
        if pr.locs and not numeric:
            continue                            # cited on the nitrogen only
        c_groups += len(numeric) if numeric else pr.mult
        cites_one = cites_one or "1" in numeric
    if c_groups == 0:
        return None
    verdicts = set()
    for c_idx, n_idx in _candidates(mol):
        if _carbon_groups(mol, c_idx, n_idx) == c_groups:
            verdicts.add(_locant_required(mol, c_idx, n_idx))
    if len(verdicts) != 1:
        return None
    required = verdicts.pop()
    if required and not cites_one:
        return SpellingFailure("P-14.3.4.4", f"the locant '1' of the group on the carbon of '{unit.parent}' "
                                             f"is omitted although a group can move between its positions")
    return None
