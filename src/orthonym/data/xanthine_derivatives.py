def _get_canonical_smiles(mol: Chem.Mol) -> str:
    """
    Get canonical SMILES for a molecule, removing explicit hydrogens.

    Args:
        mol: RDKit molecule object

    Returns:
        Canonical SMILES string
    """
    mol_no_h = Chem.RemoveHs(mol)
    return Chem.MolToSmiles(mol_no_h, canonical=True)


def identify_xanthine(mol: Chem.Mol) -> Optional[str]:
    """
    Identify if a molecule is a known xanthine derivative.

    Checks if the molecule's canonical SMILES matches any entry in the
    XANTHINE_DERIVATIVES dictionary.

    Args:
        mol: RDKit molecule object

    Returns:
        Canonical SMILES key if molecule is a known xanthine derivative,
        None otherwise.

    Examples:
        >>> mol = Chem.MolFromSmiles('Cn1cnc2c1c(=O)n(C)c(=O)n2C') # caffeine
        >>> identify_xanthine(mol)
        'Cn1cnc2c1c(=O)n(C)c(=O)n2C'
    """
    if mol is None:
        return None

    canonical = _get_canonical_smiles(mol)

    if canonical in XANTHINE_DERIVATIVES:
        return canonical

    return None


def get_xanthine_name(mol: Chem.Mol, use_common: bool = False) -> Optional[str]:
    """
    Get the IUPAC name for a xanthine derivative.

    IUPAC retained names (e.g., 'xanthine', 'hypoxanthine') always take
    priority over systematic names. These are PINs per IUPAC 2013.
    For named derivatives like caffeine, theophylline: these are common
    names (not IUPAC retained), so the systematic name is correct for PIN.

    Args:
        mol: RDKit molecule object
        use_common: If True, return common name (caffeine, theophylline, etc.)
                   If False, return systematic IUPAC name (unless retained
                   name exists, which always takes priority)

    Returns:
        IUPAC systematic or common name for the xanthine derivative,
        None if molecule is not a known xanthine.

    Examples:
        >>> mol = Chem.MolFromSmiles('O=c1[nH]c(=O)c2[nH]cnc2[nH]1') # xanthine
        >>> get_xanthine_name(mol)
        'xanthine'
        >>> mol = Chem.MolFromSmiles('Cn1cnc2c1c(=O)n(C)c(=O)n2C') # caffeine
        >>> get_xanthine_name(mol)
        '1,3,7-trimethyl-3,7-dihydro-1H-purine-2,6-dione'
        >>> get_xanthine_name(mol, use_common=True)
        'caffeine'
    """
    key = identify_xanthine(mol)
    if key is None:
        return None

    data = XANTHINE_DERIVATIVES[key]
    # IUPAC retained names always take priority (e.g., xanthine, hypoxanthine)
    retained = data.get('retained_name')
    if retained:
        return retained
    if use_common:
        return data.get('common_name')
    return data.get('systematic_name')


def get_xanthine_info(mol: Chem.Mol) -> Optional[Dict[str, Any]]:
    """
    Get full information about a xanthine derivative.

    Args:
        mol: RDKit molecule object

    Returns:
        Dict with all xanthine data (systematic_name, common_name,
        n_positions, n_substituents, indicated_h, saturation, parent),
        or None if not a known xanthine.

    Examples:
        >>> mol = Chem.MolFromSmiles('Cn1cnc2c1c(=O)n(C)c(=O)n2C') # caffeine
        >>> info = get_xanthine_info(mol)
        >>> info['n_positions']
        [1, 3, 7]
    """
    key = identify_xanthine(mol)
    if key is None:
        return None

    return XANTHINE_DERIVATIVES[key].copy()


def get_xanthine_n_positions(mol: Chem.Mol) -> Optional[List[int]]:
    """
    Get N-substitution positions for a xanthine derivative.

    Args:
        mol: RDKit molecule object

    Returns:
        List of N-positions that are substituted (e.g., [1, 3, 7] for caffeine),
        or None if not a known xanthine.
    """
    info = get_xanthine_info(mol)
    if info is None:
        return None
    return info.get('n_positions', [])


def is_xanthine_derivative(mol: Chem.Mol) -> bool:
    """
    Check if a molecule is a known xanthine derivative.

    Args:
        mol: RDKit molecule object

    Returns:
        True if molecule is a known xanthine derivative
    """
    return identify_xanthine(mol) is not None
