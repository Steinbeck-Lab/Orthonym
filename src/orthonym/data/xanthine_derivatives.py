"""
Xanthine derivatives data module for purine-based alkaloids.

This module provides data and functions for naming caffeine, theophylline,
theobromine, and related xanthine derivatives. These compounds require
specific N-position numbering that differs from standard heterocycle patterns.

IUPAC naming for xanthines:
- Parent: purine-2,6-dione (xanthine core)
- N-substitution uses numeric locants (1,3,7-trimethyl, not N,N',N''-trimethyl)
- Indicated hydrogen marks the tautomeric position (1H, 7H)
- Partial saturation uses dihydro prefix (3,7-dihydro)

Reference: IUPAC 2013 Blue Book (Purines and xanthines)
"""

