# Systematic monosaccharide engine (Phase 183, WSC-04, P-102.5)
# ============================================================================
#
# name_monosaccharide_systematic is a sibling GENERALIZATION of
# recognize_sugar_skeleton (D-01): where the clean-ring deriver fails closed on
# a deoxy / amino / uronic ring, the systematic engine classifies the modified
# positions structurally (D-04), PHYSICALLY idealizes the ring to its parent
# aldose skeleton (RWMol edit + re-CIP, Pitfall 1 — the raw modified fingerprint
# does NOT equal the clean parent, so idealization MUST be physical), recovers
# (anomer, config, base) from the gate-proven _SKELETON_FINGERPRINT_INDEX, and
# re-applies the modifications as detachable prefixes / the -uronic acid suffix
# with STRUCTURALLY-derived locants — never string surgery on a derived base
# (the contributor guide root-cause).  Fail-closed (D-11): any unrecognized modification,
# out-of-scope ring, or unindexed (C7+) fingerprint returns None so the existing
# pipeline (catalog / oxane / decomposition / acyclic) stays byte-identical.

# Explicit clean-parent-base -> uronic-tagged-base map (Warning 2 / Pitfall 5).
# The idealized fingerprint lookup recovers the CLEAN parent base
# ("glucopyranose"), but uronic_free_acid_name's map keys on the uronic-tagged
# base ("glucuronopyranose").  This is an EXPLICIT map, NEVER inline string
# substitution (str.replace / re.sub) on a derived base name.  An out-of-map
# skeleton has no verified uronic name -> the URONIC branch FAILS CLOSED.
# v23 CARB-03: completed to all 8 aldohexose uronic acids (P-102.5.6.6). Every
# free-acid name is OPSIN-round-trip verified; the idealize->recover chain was
# confirmed to recover the correct clean parent hexose for each (the fingerprint
# index carries all 8 D/L hexopyranoses since CARB-02), so the two maps are the
# only gate. Pentoses are excluded: an aldopentopyranose has no exocyclic
# terminal CH2OH to oxidize (its "C5" is the ring CH2), so there is no
# analogous pyranuronic acid.
_URONIC_STEM_MAP = {
    "allopyranose": "alluronopyranose",
    "altropyranose": "altruronopyranose",
    "glucopyranose": "glucuronopyranose",
    "mannopyranose": "mannuronopyranose",
    "gulopyranose": "guluronopyranose",
    "idopyranose": "iduronopyranose",
    "galactopyranose": "galacturonopyranose",
    "talopyranose": "taluronopyranose",
}


def _classify_sugar_positions(mol, ring, ring_oxygen, anomeric_idx):
    """Classify a single sugar ring's modified positions structurally (D-04).

    Numbers the ring per IUPAC carbohydrate locants (anomeric C = C1; walk away
    from the ring-O for C2..C5 on a pyranose / C2..C4 on a furanose; the
    exocyclic CH2OH/COOH carbon = the next locant, C6 for a hexose) and
    classifies each position against the idealized hydroxyl pattern:

    * a ring carbon whose only exocyclic carbon is a bare terminal methyl
      (no exocyclic O, degree 1) -> DEOXY at that exocyclic carbon's locant
      (the 6-deoxy methyl tail, P-102.5.3);
    * a ring carbon bearing an exocyclic nitrogen -> AMINO at the ring carbon's
      locant, cited ``x-amino-x-deoxy`` (P-102.5.4 — the N replaces the C-OH);
    * a ring carbon whose exocyclic carbon is oxidized to a carboxyl
      (CH2OH -> COOH, an exocyclic carbon with two O neighbours incl. a double
      bond) -> URONIC at that exocyclic carbon's locant (P-102.5.6.6).

    Returns a dict ``{"deoxy": [locants], "amino": [locants], "uronic":
    [locants]}`` of STRUCTURALLY-derived locants, or ``None`` if the ring carries
    a modification this classifier does not recognize (fail-closed, D-11) — so
    the engine never emits a partial / guessed sugar name.  A clean ring yields
    all-empty lists (-> the engine returns None: a clean ring is
    recognize_sugar_skeleton's / lookup_sugar's job).
    """
    ringset = set(ring)
    adjacency = {
        idx: [
            n.GetIdx()
            for n in mol.GetAtomWithIdx(idx).GetNeighbors()
            if n.GetIdx() in ringset
        ]
        for idx in ringset
    }
    # IUPAC ring-carbon numbering: start at the anomeric C (C1), step to the
    # ring neighbour that is NOT the ring oxygen, then walk the ring.
    non_oxygen_nbrs = [x for x in adjacency[anomeric_idx] if x != ring_oxygen]
    if len(non_oxygen_nbrs) != 1:
        return None
    order = [anomeric_idx]
    prev, cur = anomeric_idx, non_oxygen_nbrs[0]
    while cur != anomeric_idx:
        order.append(cur)
        nxt = [x for x in adjacency[cur] if x != prev]
        if not nxt:
            break
        prev, cur = cur, nxt[0]
    ring_carbons = [i for i in order if mol.GetAtomWithIdx(i).GetSymbol() == "C"]
    # Map each ring carbon to its IUPAC locant (C1..Cn).
    locant_of = {c: k + 1 for k, c in enumerate(ring_carbons)}
    last_ring_locant = len(ring_carbons)  # C5 on a pyranose, C4 on a furanose

    found = {"deoxy": [], "amino": [], "uronic": [], "halo": []}
    for ring_c in ring_carbons:
        loc = locant_of[ring_c]
        atom = mol.GetAtomWithIdx(ring_c)
        for nbr in atom.GetNeighbors():
            if nbr.GetIdx() in ringset:
                continue
            sym = nbr.GetSymbol()
            if sym == "O":
                continue  # hydroxyl / anomeric-O / glycosidic-O (clean)
            if sym in ("F", "Cl", "Br", "I"):
                # ring C-OH replaced by C-halogen: a deoxy-halo sugar (e.g.
                # 2-deoxy-2-fluoro-D-galactopyranose, P-102.5.3 + halogeno prefix).
                # Only a terminal monovalent halogen substituting the ring C-OH
                # is in scope; the halogen idealizes back to -OH (halogen -> O),
                # so the position is BOTH deoxy and halo.  A halogen that is not a
                # simple ring-carbon substituent (degree != 1) is out of scope ->
                # fail closed (never a wrong / partial name).
                if nbr.GetDegree() != 1:
                    return None
                found["halo"].append((loc, sym))
                continue
            if sym == "N":
                # ring C-OH replaced by C-N: amino at this ring carbon's locant.
                # Only a BARE primary amine (-NH2) is the P-102.5.4 subtractive
                # `amino` class.  An N-acyl / N-alkyl / charged nitrogen is a
                # distinct (out-of-scope) regime: its decoration is invisible to
                # the ring-CIP fingerprint, so classifying it as plain `amino`
                # would silently DROP the substituent and ship a wrong name
                # (CR-01).  Fail closed instead (the contributor guide fail-closed mandate):
                # the structure cascade-continues to the catalog / decomposition.
                # Bare -NH2 == the N's only heavy-atom neighbour is this ring
                # carbon (heavy degree 1), neutral, and carries its two H.
                heavy_nbrs = sum(
                    1 for x in nbr.GetNeighbors() if x.GetAtomicNum() > 1
                )
                if (
                    heavy_nbrs != 1
                    or nbr.GetFormalCharge() != 0
                    or nbr.GetTotalNumHs() < 2
                ):
                    return None  # N-acyl / N-alkyl / charged N -> out of scope
                found["amino"].append(loc)
            elif sym == "C":
                # exocyclic carbon: CH2OH (clean) / CH3 (deoxy) / COOH (uronic).
                o_neighbors = [
                    x for x in nbr.GetNeighbors() if x.GetSymbol() == "O"
                ]
                has_double_o = any(
                    b.GetBondTypeAsDouble() == 2.0 for b in nbr.GetBonds()
                )
                exo_locant = loc + 1  # the exocyclic carbon's locant (C6 on hexose)
                if has_double_o and len(o_neighbors) >= 2:
                    found["uronic"].append(exo_locant)  # CH2OH -> COOH
                elif not o_neighbors and nbr.GetDegree() == 1:
                    found["deoxy"].append(exo_locant)  # bare terminal CH3
                elif len(o_neighbors) == 1 and not has_double_o:
                    pass  # clean CH2OH exocyclic carbon (C6) — no modification
                else:
                    return None  # unrecognized exocyclic carbon (fail-closed)
            else:
                return None  # unrecognized heteroatom substituent (fail-closed)
    # If a ring carbon is deoxy at its ring locant (an exocyclic O simply
    # missing on a non-terminal carbon) it would surface as a clean carbon here;
    # this engine handles the terminal 6-deoxy + amino + uronic classes only —
    # additional deoxy positions are out of scope and would idealize-mismatch,
    # caught downstream by the fingerprint lookup.  Record the last ring locant
    # so the caller can sanity-check hexose vs pentose if needed.
    found["_last_ring_locant"] = last_ring_locant
    return found


def _idealize_to_parent(mol):
    """Physically restore a modified sugar ring to its parent aldose skeleton.

    Builds a ``Chem.RWMol`` copy and applies *every* classified modification
    edit back toward the clean hexose/pentose OH/H/CH2OH skeleton (RESEARCH §1,
    each edit VERIFIED to reproduce the canonical SMILES of clean
    beta-D-glucopyranose):

    * DEOXY  -> add an exocyclic O to each bare terminal ring-attached methyl C
      (CH3 -> CH2OH);
    * URONIC -> ``RemoveAtom`` the double-bonded O on each ring-attached COOH
      carbon (COOH -> CH2OH);
    * AMINO  -> ``SetAtomicNum(8)`` on each (bare primary) nitrogen
      (C-N -> C-OH).

    A modified sugar may carry SEVERAL of these at once (e.g. a 6-deoxy-2-amino
    hexose).  Treating them as mutually exclusive ``if/elif/else`` (CR-02a) only
    idealizes ONE position and leaves the rest, producing a structure whose
    fingerprint does NOT represent the true idealized parent — and shipping a
    wrong recovered base/anomer/config.  We therefore enumerate ALL modification
    sites up-front (on the un-edited copy, so index/degree tests are stable) and
    apply every edit; nothing is left un-idealized.  The downstream
    ``_is_clean_sugar_ring`` re-check + the fingerprint lookup then either
    recover a clean parent or fail closed (never a partially-idealized guess).

    Idealization MUST be physical, not analytic: the raw modified-sugar CIP
    fingerprint does NOT match the clean parent (Pitfall 1 — e.g. the uronic C6
    carboxyl re-ranks C5 R->S).  After the edits the molecule is sanitized and
    re-CIP'd by the caller before fingerprinting.

    Mirrors the in-tree RWMol-edit-then-sanitize analog
    ``rules/lipids.py::_acid_fragment_name``.  Returns the idealized (NEW) mol,
    or ``None`` on sanitize failure (T-183-04: never crash on a malformed ring).
    The input mol is never mutated (pure — operates on an RWMol copy).
    """
    if mol is None:
        return None
    rw = Chem.RWMol(mol)

    # Enumerate ALL modification sites on the un-edited copy so the structural
    # predicates (degree, neighbour symbols, double bonds) are evaluated against
    # the original molecule and are not perturbed by an earlier edit.
    nitrogen_idxs = [a.GetIdx() for a in rw.GetAtoms() if a.GetSymbol() == "N"]
    # Halo (deoxy-halogeno): each monovalent halogen substituting a ring C-OH is
    # restored to -OH (halogen -> O -> -OH after sanitize), mirroring the amino
    # N -> O edit.  classify has already gated these to degree-1 ring-carbon
    # substituents, so a plain SetAtomicNum(8) is valence-safe.
    halogen_idxs = [
        a.GetIdx() for a in rw.GetAtoms()
        if a.GetSymbol() in ("F", "Cl", "Br", "I")
    ]
    # Uronic carboxyl carbons: a carbon with two O neighbours and a C=O bond;
    # record the double-bonded O to remove (COOH -> CH2OH).
    carbonyl_o_idxs = []
    for a in rw.GetAtoms():
        if a.GetSymbol() != "C":
            continue
        if sum(1 for n in a.GetNeighbors() if n.GetSymbol() == "O") != 2:
            continue
        for b in a.GetBonds():
            if b.GetBondType() == Chem.BondType.DOUBLE:
                other = b.GetOtherAtom(a)
                if other.GetSymbol() == "O":
                    carbonyl_o_idxs.append(other.GetIdx())
    # Deoxy: bare terminal (degree-1) carbons get an exocyclic O (CH3 -> CH2OH).
    deoxy_methyl_idxs = [
        a.GetIdx()
        for a in rw.GetAtoms()
        if a.GetSymbol() == "C" and a.GetDegree() == 1
    ]

    try:
        # AMINO: every (bare) nitrogen -> O.  No index shift.
        for idx in nitrogen_idxs:
            rw.GetAtomWithIdx(idx).SetAtomicNum(8)
        # HALO: every ring-carbon halogen -> O (-> -OH).  No index shift.
        for idx in halogen_idxs:
            rw.GetAtomWithIdx(idx).SetAtomicNum(8)
        # DEOXY: add the exocyclic O on each bare terminal carbon.  Additions
        # append new indices and never shift existing ones, so do them before
        # any RemoveAtom.
        for methyl in deoxy_methyl_idxs:
            o = rw.AddAtom(Chem.Atom(8))
            rw.AddBond(methyl, o, Chem.BondType.SINGLE)
        # URONIC: remove each carbonyl =O.  RemoveAtom re-indexes higher atoms,
        # so delete in descending order to keep the remaining indices valid.
        for o_idx in sorted(set(carbonyl_o_idxs), reverse=True):
            rw.RemoveAtom(o_idx)
    except (StopIteration, RuntimeError, ValueError):
        return None  # an expected modification atom was not found -> fail-closed
    m2 = rw.GetMol()
    try:
        Chem.SanitizeMol(m2)
    except Exception:
        try:
            Chem.SanitizeMol(
                m2,
                sanitizeOps=Chem.SanitizeFlags.SANITIZE_ALL
                ^ Chem.SanitizeFlags.SANITIZE_KEKULIZE,
            )
        except Exception:
            return None
    return m2


def _mono_name_rt_ok(mol, name: str) -> bool:
    """Return True iff the systematic-mono ``name`` OPSIN-round-trips to ``mol``.

    Defense-in-depth RT backstop (WR-01) mirroring
    ``rules.oligosaccharides._sugar_name_rt_ok`` and
    ``rules.natural_products._alpha_beta_rt_ok``: the disaccharide path gates
    every assembled name on an OPSIN round-trip, but the mono path shipped its
    name ungated — which is precisely why a wrong systematic name (a slipped
    modification class, a non-PIN ``2,6-deoxy`` rendering) could ship instead of
    cascade-continuing.

    Fail-OPEN: when OPSIN/Java is unavailable the round-trip cannot be checked,
    so the name is shipped (the SUB-03 validity-gate posture; CI without Java is
    unaffected).  When OPSIN IS available, a name that does not round-trip to the
    input structure is rejected (-> ``None`` -> existing pipeline), guaranteeing
    no wrong name ships even if a future modification class slips the classifier.

    The import is lazy (and ``data`` -> ``validation`` is acyclic), so module
    import stays cheap and free of cycles.
    """
    try:
        from ..validation.opsin_roundtrip import (
            opsin_roundtrip_check, _find_opsin_jar, _java_available,
        )
        if _find_opsin_jar() is None or not _java_available():
            return True  # fail-OPEN
        smi = Chem.MolToSmiles(mol)
        return bool(opsin_roundtrip_check(smi, name).get("passed"))
    except (OSError, ValueError, RuntimeError):
        # Expected operational failures (subprocess / sanitize / indexing) ->
        # fail-OPEN so a genuinely-absent or flaky OPSIN never suppresses a name.
        return True


def name_monosaccharide_systematic(mol) -> Optional[str]:
    """Systematic P-102.5 name for a non-cataloged deoxy/amino/uronic sugar ring.

    A sibling GENERALIZATION of :func:`recognize_sugar_skeleton` (D-01): for a
    single 5/6-membered sugar ring that the clean-ring deriver fails closed on
    (because it carries a deoxy / amino / uronic modification), this engine

    1. reuses the analog's gates (single ring; one ring-O; one anomeric C via
       :func:`_locate_anomeric_carbon`) and derives the ring size ->
       ``pyranose`` (6) / ``furanose`` (5) (P-102.3.4);
    2. classifies the modified positions STRUCTURALLY with IUPAC-derived locants
       (:func:`_classify_sugar_positions`, D-04);
    3. PHYSICALLY idealizes the ring to its parent aldose skeleton
       (:func:`_idealize_to_parent`, the three RESEARCH §1 edits), re-runs
       ``rdCIPLabeler.AssignCIPLabels``, and recovers ``(anomer, config, base)``
       from the gate-proven :data:`_SKELETON_FINGERPRINT_INDEX` (Pitfall 1 — the
       raw modified fingerprint does NOT equal the clean parent);
    4. assembles the name (D-04):

       * URONIC (P-102.5.6.6): map the idealized clean ``base`` to the
         uronic-tagged base via the explicit :data:`_URONIC_STEM_MAP`
         (Warning 2 — NEVER inline ``str.replace``/``re.sub``), then emit
         :func:`uronic_free_acid_name` -> ``beta-D-glucopyranuronic acid``;
       * DEOXY / AMINO (P-102.5.3 / P-102.5.4): emit alphabetized detachable
         prefixes with their derived locants ->
         ``{prefixes}-{anomer}-{config}-{base}`` (e.g. ``6-deoxy-beta-D-
         glucopyranose``, ``3-amino-3-deoxy-beta-D-glucopyranose``); ``amino``
         alphabetizes before ``deoxy``.

    Fail-closed (D-11): returns ``None`` for a non-sugar, a clean cataloged ring
    (that is ``lookup_sugar``'s job, D-05), a C-glycoside / anhydro ring (no
    clean idealized fingerprint), an out-of-map uronic skeleton, or a C7+ cyclic
    sugar (no :data:`_SKELETON_FINGERPRINT_INDEX` entry, Assumption A3) — so the
    existing pipeline stays byte-identical.  Descriptors are ASCII (``beta-D-``,
    Pitfall 6).  The input mol is never mutated.

    Args:
        mol: RDKit Mol of a free monosaccharide (anomeric -OH present).

    Returns:
        The systematic P-102.5 name, or ``None`` when out of scope.

    Examples:
        >>> from rdkit import Chem
        >>> m = Chem.MolFromSmiles("C[C@H]1O[C@@H](O)[C@H](O)[C@@H](O)[C@@H]1O")
        >>> name_monosaccharide_systematic(m)
        '6-deoxy-beta-D-glucopyranose'
    """
    if mol is None:
        return None
    ri = mol.GetRingInfo()
    if ri.NumRings() != 1:
        return None
    ring = ri.AtomRings()[0]
    if len(set(ring)) not in (5, 6):
        return None
    ring_oxygens = [i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O"]
    if len(ring_oxygens) != 1:
        return None
    ring_oxygen = ring_oxygens[0]

    anomeric_idx = _locate_anomeric_carbon(mol, ring, ring_oxygen)
    if anomeric_idx is None or anomeric_idx not in set(ring):
        return None

    ring_form = "pyranose" if len(set(ring)) == 6 else "furanose"

    # (2) Classify the modified positions structurally (D-04).
    modifications = _classify_sugar_positions(mol, ring, ring_oxygen, anomeric_idx)
    if modifications is None:
        return None
    deoxy_locants = sorted(modifications["deoxy"])
    amino_locants = sorted(modifications["amino"])
    uronic_locants = sorted(modifications["uronic"])
    halo_locants = sorted(modifications.get("halo", []))  # [(locant, halogen)]
    if not (deoxy_locants or amino_locants or uronic_locants or halo_locants):
        # A clean ring is recognize_sugar_skeleton's / lookup_sugar's job.
        return None

    # (3) Physically idealize the ring to its parent skeleton and recover
    # (anomer, config, base) from the proven fingerprint index (D-01).
    idealized = _idealize_to_parent(mol)
    if idealized is None:
        return None
    _ensure_cip(idealized)
    ideal_ri = idealized.GetRingInfo()
    if ideal_ri.NumRings() != 1:
        return None
    ideal_ring = ideal_ri.AtomRings()[0]
    ideal_ring_oxygens = [
        i for i in ideal_ring if idealized.GetAtomWithIdx(i).GetSymbol() == "O"
    ]
    if len(ideal_ring_oxygens) != 1:
        return None
    ideal_ring_oxygen = ideal_ring_oxygens[0]
    ideal_anomeric = _locate_anomeric_carbon(idealized, ideal_ring, ideal_ring_oxygen)
    if ideal_anomeric is None:
        return None
    fingerprint = _ring_cip_fingerprint(
        idealized, ideal_ring, ideal_ring_oxygen, ideal_anomeric
    )
    if fingerprint is None:
        return None
    recovered = _SKELETON_FINGERPRINT_INDEX.get(fingerprint)
    if recovered is None:
        return None  # C7+ cyclic / unindexed fingerprint -> fail-closed (A3)
    anomer, config, base = recovered
    # The idealized base must carry the ring-form designator we derived; the
    # fingerprint index keys all 8 D-hexoses + pentoses in pyranose/furanose.
    if ring_form not in base:
        return None

    # (4) Assemble (D-04) -> a single `candidate`, gated by the RT backstop
    # (WR-01) at the function tail so no wrong name ships.
    if uronic_locants:
        # A uronic sugar is named purely by the -uronic acid suffix; it must not
        # co-occur with deoxy/amino/halo in this engine's scope (fail-closed).
        if deoxy_locants or amino_locants or halo_locants:
            return None
        uronic_base = _URONIC_STEM_MAP.get(base)
        if uronic_base is None:
            return None  # out-of-map skeleton has no verified uronic name (D-11)
        candidate = uronic_free_acid_name(anomer, config, uronic_base)
    else:
        # DEOXY / AMINO / HALO: build alphabetized detachable prefixes WITH
        # structural locants (never string surgery on the derived base).
        # P-102.5.4 cites an amino sugar as ``x-amino-x-deoxy`` (the N replaces a
        # C-OH, so each amino locant is also a deoxy locant); a halogeno sugar is
        # likewise ``x-deoxy-x-halogeno`` (the halogen replaces a C-OH), so each
        # halo locant is also a deoxy locant.
        prefix_terms = []  # (alpha-sort-key, rendered-term)
        all_deoxy = sorted(
            set(deoxy_locants) | set(amino_locants) | {loc for loc, _ in halo_locants}
        )
        if amino_locants:
            prefix_terms.append(
                ("amino", f"{','.join(str(x) for x in amino_locants)}-amino")
            )
        # HALO: group by halogen, cite locants + multiplier, alpha-key = halogen
        # name (fluoro/chloro/bromo/iodo — ordered ignoring the di/tri multiplier).
        _HALO_NAME = {"F": "fluoro", "Cl": "chloro", "Br": "bromo", "I": "iodo"}
        _HALO_MULT = {1: "", 2: "di", 3: "tri", 4: "tetra"}
        halo_by_sym: Dict[str, list] = {}
        for loc, sym in halo_locants:
            halo_by_sym.setdefault(sym, []).append(loc)
        for sym, locs in halo_by_sym.items():
            hname = _HALO_NAME[sym]
            mult = _HALO_MULT.get(len(locs))
            if mult is None:
                return None  # >4 of one halogen -> out of scope, fail-closed
            locs = sorted(locs)
            prefix_terms.append(
                (hname, f"{','.join(str(x) for x in locs)}-{mult}{hname}")
            )
        if all_deoxy:
            prefix_terms.append(
                ("deoxy", f"{','.join(str(x) for x in all_deoxy)}-deoxy")
            )
        # Alphabetize the detachable prefixes (amino < bromo < chloro < deoxy < ...).
        prefix_terms.sort(key=lambda t: t[0])
        prefix_str = "-".join(term for _, term in prefix_terms)

        # Emit the configurational descriptor whenever it is known, even if the
        # anomeric configuration is undefined (the anomeric C carries no stereo):
        # "2-deoxy-2-fluoro-D-galactopyranose" (anomer unspecified) is the correct
        # PIN, not the D-dropped "…-galactopyranose".  config is always recovered
        # from the gate-proven fingerprint index, so it is reliable.
        if anomer and config:
            descriptor = f"{anomer}-{config}-"
        elif config:
            descriptor = f"{config}-"
        else:
            descriptor = ""
        if prefix_str:
            candidate = f"{prefix_str}-{descriptor}{base}"
        else:
            candidate = f"{descriptor}{base}"

    # RT backstop (WR-01, defense-in-depth): before shipping the systematic name,
    # verify it OPSIN-round-trips to the input structure (fail-OPEN when Java/JAR
    # absent).  This makes the whole engine fail-closed by construction even if a
    # future modification class slips the structural classifier.
    if candidate is None:
        return None
    if not _mono_name_rt_ok(mol, candidate):
        return None
    return candidate


def name_free_sugar(mol, canonical_smiles: str) -> Optional[str]:
    """Name a free (non-glycosidic) monosaccharide: catalog-join then systematic.

    This is the exact catalog-join + systematic cascade the carbohydrate dispatch
    handler used inline (``routing/dispatch_table._handle_carbohydrate_lookup``);
    factored here so the free-sugar-ester path (:func:`name_sugar_ester`) can name
    the residual sugar through the SAME code (DRY, no drift). Returns the sugar
    name or ``None`` (a catalog uronic-base whose :func:`uronic_free_acid_name`
    fails, or an out-of-scope ring). Byte-identical to the handler's prior logic.
    """
    sugar_info = lookup_sugar(canonical_smiles)
    if sugar_info is not None:
        anomer, config, base_name = sugar_info
        # D-10: a cataloged uronic base emits the OPSIN-parseable free-acid form.
        if "urono" in base_name:
            return uronic_free_acid_name(anomer, config, base_name)
        # F-CATALOG-JOIN (v23 Phase 5): a prefix-bearing catalog base needs the
        # configurational descriptor inserted BEFORE the stem, AFTER the prefixes.
        if (anomer or config) and "-" in base_name:
            prefix_block, stem = base_name.rsplit("-", 1)
            descriptor = "-".join(p for p in (anomer, config) if p)
            return f"{prefix_block}-{descriptor}-{stem}"
        parts = [p for p in (anomer, config) if p]
        parts.append(base_name)
        return "-".join(parts)
    # Catalog miss -> systematic monosaccharide.
    return name_monosaccharide_systematic(mol)


def _sugar_carbon_locants(mol, ring, ring_oxygen, anomeric_idx):
    """Map each sugar carbon (ring carbon + its exocyclic carbon) to its IUPAC
    carbohydrate locant.  Mirrors the numbering walk in
    :func:`_classify_sugar_positions` (anomeric C = C1; step to the ring neighbour
    that is NOT the ring oxygen, then walk the ring; the exocyclic carbon of ring
    carbon *n* is locant *n+1*, so C5's exocyclic CH2OH is C6 on a hexopyranose).

    Returns ``{atom_idx: locant}`` covering every ring carbon and each ring
    carbon's single exocyclic carbon, or ``None`` if the ring is not a linear
    single-anomeric chain (fail-closed).
    """
    ringset = set(ring)
    adjacency = {
        idx: [
            n.GetIdx()
            for n in mol.GetAtomWithIdx(idx).GetNeighbors()
            if n.GetIdx() in ringset
        ]
        for idx in ringset
    }
    non_oxygen_nbrs = [x for x in adjacency[anomeric_idx] if x != ring_oxygen]
    if len(non_oxygen_nbrs) != 1:
        return None
    order = [anomeric_idx]
    prev, cur = anomeric_idx, non_oxygen_nbrs[0]
    while cur != anomeric_idx:
        order.append(cur)
        nxt = [x for x in adjacency[cur] if x != prev]
        if not nxt:
            break
        prev, cur = cur, nxt[0]
    ring_carbons = [i for i in order if mol.GetAtomWithIdx(i).GetSymbol() == "C"]
    # 2-ketose numbering (P-102): the anomeric carbon of a ketose (fructose,
    # sorbose, ...) bears an exocyclic carbon — the C1 CH2OH — so the anomeric
    # carbon is C2, not C1.  An aldose anomeric carbon has NO exocyclic carbon
    # (only -OH/-H there), so this branch never fires and aldose numbering below
    # stays byte-identical.
    anomeric_exo_c = [
        n.GetIdx()
        for n in mol.GetAtomWithIdx(anomeric_idx).GetNeighbors()
        if n.GetIdx() not in ringset and n.GetSymbol() == "C"
    ]
    is_ketose = len(anomeric_exo_c) == 1
    offset = 2 if is_ketose else 1
    locant_of = {c: k + offset for k, c in enumerate(ring_carbons)}
    result = dict(locant_of)
    if is_ketose:
        result[anomeric_exo_c[0]] = 1  # C1 = the exocyclic carbon on anomeric C2
    for ring_c in ring_carbons:
        if is_ketose and ring_c == anomeric_idx:
            continue  # its exocyclic carbon is C1, assigned above
        loc = locant_of[ring_c]
        for nbr in mol.GetAtomWithIdx(ring_c).GetNeighbors():
            if nbr.GetIdx() in ringset:
                continue
            if nbr.GetSymbol() == "C":
                result[nbr.GetIdx()] = loc + 1
    return result


def _find_sugar_oxoacid_ester(mol):
    """Cheap STRUCTURAL detector for free-sugar phosphate/sulfate ester(s).

    Returns a LIST ``[(sugar_c_idx, ester_o_idx, central_idx, locant, word), ...]``
    (1–3 esters) for a single sugar ring bearing ``-O-PO(...)`` / ``-O-SO2(...)``
    ester(s) on ring or exocyclic carbons, else ``None`` (fail-closed).  Pure RDKit
    walks + the class-agnostic protonation->word maps — NO OPSIN, so it is safe to
    call from the dispatch predicate.  A P-O-P bridge (di/tri-phosphate, 183/184
    territory) returns ``None`` per-ester; >3 esters returns ``None``.
    """
    if mol is None:
        return None
    ri = mol.GetRingInfo()
    # A phosphate/sulfate ester group adds no ring, so the sugar must be the ONLY
    # ring (a glycoside/oligo has >1 sugar ring -> not this path).
    if ri.NumRings() != 1:
        return None
    ring = ri.AtomRings()[0]
    if len(set(ring)) not in (5, 6):
        return None
    ring_oxygens = [i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O"]
    if len(ring_oxygens) != 1:
        return None
    ring_oxygen = ring_oxygens[0]
    anomeric_idx = _locate_anomeric_carbon(mol, ring, ring_oxygen)
    if anomeric_idx is None or anomeric_idx not in set(ring):
        return None
    locants = _sugar_carbon_locants(mol, ring, ring_oxygen, anomeric_idx)
    if locants is None:
        return None

    # Find the ester linker(s): an O with no H bonded to a sugar carbon AND to a
    # P or S acid centre.  1-3 -> named; else fail-closed.
    esters = []  # (sugar_carbon_idx, ester_o_idx, central_idx)
    for atom in mol.GetAtoms():
        if atom.GetAtomicNum() != 8 or atom.GetTotalNumHs() > 0:
            continue
        nbrs = list(atom.GetNeighbors())
        if len(nbrs) != 2:
            continue
        sugar_c = central = None
        for n in nbrs:
            if n.GetAtomicNum() == 6 and n.GetIdx() in locants:
                sugar_c = n.GetIdx()
            elif n.GetAtomicNum() in (15, 16):
                central = n.GetIdx()
        if sugar_c is not None and central is not None:
            esters.append((sugar_c, atom.GetIdx(), central))
    if not (1 <= len(esters) <= 3):
        return None

    from orthonym.rules.conjugate_controller import (
        PHOSPHATE_WORD,
        SULFATE_WORD,
        _count_double_bonded_oxygens,
        _terminal_acid_oxygens,
    )

    def _ester_word(ester_o, central):
        """Protonation-state word for one phosphate/sulfate ester, or None."""
        central_atom = mol.GetAtomWithIdx(central)
        z = central_atom.GetAtomicNum()
        if z == 16:  # sulfate: S with exactly two =O
            if _count_double_bonded_oxygens(mol, central) != 2:
                return None
            prot, _anion = _terminal_acid_oxygens(mol, central, ester_o)
            return SULFATE_WORD.get(prot)
        if z == 15:  # phosphate (mono only): P with one =O and no second P
            if _count_double_bonded_oxygens(mol, central) != 1:
                return None
            for n in central_atom.GetNeighbors():
                if n.GetAtomicNum() == 8 and n.GetIdx() != ester_o:
                    if any(
                        nn.GetAtomicNum() == 15 and nn.GetIdx() != central
                        for nn in n.GetNeighbors()
                    ):
                        return None  # P-O-P / di-tri-phosphate -> out of scope
            prot, _anion = _terminal_acid_oxygens(mol, central, ester_o)
            return PHOSPHATE_WORD.get(prot)
        return None

    result = []
    for sugar_c, ester_o, central in esters:
        word = _ester_word(ester_o, central)
        if word is None:
            return None
        result.append((sugar_c, ester_o, central, locants[sugar_c], word))
    return result


def _find_sugar_acyl_esters(mol):
    """Cheap STRUCTURAL detector for free-sugar O-acyl ester(s) (BB P-102.5.6.1.1).

    Returns a locant-sorted list ``[(sugar_c, ester_o, acyl_c, locant), ...]`` for
    every ester O (Z=8, no H, degree 2) bonding a NON-anomeric sugar carbon to a
    carbonyl carbon (an acyl C=O), else ``None`` (fail-closed).  Pure RDKit walks —
    NO OPSIN — so it is safe to call from the dispatch predicate.  An O-acyl at the
    ANOMERIC position is a glycosyl ester (183/184 territory, out of scope) -> the
    whole molecule fails closed.
    """
    if mol is None:
        return None
    ri = mol.GetRingInfo()
    # An acyl group MAY carry its own ring (benzoate -> phenyl), so — unlike the
    # phosphate/sulfate detector — do NOT require a single ring.  Identify THE
    # sugar ring: a 5/6-membered ring with exactly one ring oxygen and the rest
    # carbons.  Require exactly one such ring (a glycoside/oligo has >1).
    sugar_rings = [
        r for r in ri.AtomRings()
        if len(r) in (5, 6)
        and sum(1 for i in r if mol.GetAtomWithIdx(i).GetSymbol() == "O") == 1
        and sum(1 for i in r if mol.GetAtomWithIdx(i).GetSymbol() == "C") == len(r) - 1
    ]
    if len(sugar_rings) != 1:
        return None
    ring = sugar_rings[0]
    ring_oxygen = next(
        i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O"
    )
    anomeric_idx = _locate_anomeric_carbon(mol, ring, ring_oxygen)
    if anomeric_idx is None or anomeric_idx not in set(ring):
        return None
    locants = _sugar_carbon_locants(mol, ring, ring_oxygen, anomeric_idx)
    if locants is None:
        return None
    esters = []
    for atom in mol.GetAtoms():
        if atom.GetAtomicNum() != 8 or atom.GetTotalNumHs() > 0:
            continue
        nbrs = list(atom.GetNeighbors())
        if len(nbrs) != 2:
            continue
        sugar_c = acyl_c = None
        for n in nbrs:
            if n.GetAtomicNum() == 6 and n.GetIdx() in locants:
                sugar_c = n.GetIdx()
            elif n.GetAtomicNum() == 6 and any(
                b.GetBondType() == Chem.BondType.DOUBLE
                and b.GetOtherAtom(n).GetAtomicNum() == 8
                for b in n.GetBonds()
            ):
                acyl_c = n.GetIdx()  # carbonyl carbon (an acyl group)
        if sugar_c is not None and acyl_c is not None:
            if sugar_c == anomeric_idx:
                return None  # anomeric O-acyl = glycosyl ester -> out of scope
            esters.append((sugar_c, atom.GetIdx(), acyl_c, locants[sugar_c]))
    if not esters:
        return None
    esters.sort(key=lambda t: t[3])
    return esters


def _is_uncataloged_ulosonic_acid(mol, canonical_smiles):
    """VETO (W6B-T7, accuracy-first): True for a 2-ulosonic-acid-shaped ring — a
    ketal ring carbon bearing ring-O + -OH + -COOH, plus an exocyclic polyol side
    chain (>=2 hydroxylated exocyclic carbons) — that is NOT in the sugar catalog.

    The general ring-carboxylic namer ships a stereo-DROPPING (RT-failing)
    '...oxane-carboxylic acid' name for these (an uncataloged KDN/Neu5Ac
    stereoisomer), so the carbohydrate handler fails closed (returns '') instead of
    letting it fall through.  Returns False for cataloged ulosonics (lookup_sugar
    names them) and for ordinary oxane-carboxylic acids (no ketal-OH, or no polyol
    tail).  Pure RDKit; NO OPSIN, so it is safe in the dispatch predicate.
    """
    if mol is None:
        return False
    if lookup_sugar(canonical_smiles) is not None:
        return False  # cataloged -> named, never vetoed
    # The veto exists to stop a STEREO-DROPPING name; if the molecule has no
    # defined stereocentre there is nothing to drop, so the general name is valid
    # -> do NOT veto (review W6B finding: avoid refusing a stereo-free ulosonic).
    if not any(a.GetChiralTag() != Chem.ChiralType.CHI_UNSPECIFIED
               for a in mol.GetAtoms()):
        return False
    ri = mol.GetRingInfo()
    ketal_acid = False
    for ring in ri.AtomRings():
        if len(ring) not in (5, 6):
            continue
        ringset = set(ring)
        ring_os = [i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O"]
        if len(ring_os) != 1:
            continue
        for i in ring:
            a = mol.GetAtomWithIdx(i)
            if a.GetSymbol() != "C":
                continue
            if not any(nb.GetIdx() in ring_os for nb in a.GetNeighbors()):
                continue  # not the ring-O-bearing (anomeric/ketal) carbon
            exo = [nb for nb in a.GetNeighbors() if nb.GetIdx() not in ringset]
            has_oh = any(
                nb.GetSymbol() == "O" and nb.GetTotalNumHs() > 0 for nb in exo
            )
            has_cooh = any(
                nb.GetSymbol() == "C"
                and any(b.GetBondType() == Chem.BondType.DOUBLE
                        and b.GetOtherAtom(nb).GetSymbol() == "O"
                        for b in nb.GetBonds())
                and any(nn.GetSymbol() == "O" and nn.GetTotalNumHs() > 0
                        for nn in nb.GetNeighbors())
                for nb in exo
            )
            if has_oh and has_cooh:
                ketal_acid = True
    if not ketal_acid:
        return False
    # Require an exocyclic polyol side chain: >=2 non-ring carbons (other than the
    # carboxyl carbon) that each bear an -OH (KDO tail=2, KDN tail=3).
    polyol_c = 0
    for atom in mol.GetAtoms():
        if atom.GetSymbol() != "C" or atom.IsInRing():
            continue
        if any(b.GetBondType() == Chem.BondType.DOUBLE
               and b.GetOtherAtom(atom).GetSymbol() == "O" for b in atom.GetBonds()):
            continue  # skip the carboxyl carbon
        if any(nb.GetSymbol() == "O" and nb.GetTotalNumHs() > 0
               for nb in atom.GetNeighbors()):
            polyol_c += 1
    return polyol_c >= 2


def _acyl_to_ate_word(mol, acyl_c, ester_o, sugar_c):
    """Reconstruct the free carboxylic acid R-C(=O)-OH of an O-acyl ester and
    return its acylate word (``benzoate`` / ``acetate`` / ``formate`` /
    ``propanoate`` / ...).  Cleaves the sugar_c—ester_o bond, keeps the acyl-side
    fragment (its ester-O relaxes to the acid -OH), names it via the acid path, and
    applies the P-65.3.1 acid->ester transform (``…oic acid``->``…oate``;
    ``…ic acid``->``…ate``).  ``None`` if the fragment does not name as a
    carboxylic acid (fail-closed)."""
    bond = mol.GetBondBetweenAtoms(sugar_c, ester_o)
    if bond is None:
        return None
    try:
        frag = Chem.FragmentOnBonds(
            mol, [bond.GetIdx()], addDummies=True, dummyLabels=[(0, 0)]
        )
        mapping = []
        frags = Chem.GetMolFrags(
            frag, asMols=True, sanitizeFrags=False, fragsMolAtomMapping=mapping
        )
    except Exception:
        return None
    acid_frag = None
    for fm, mp in zip(frags, mapping):
        if acyl_c in mp:
            acid_frag = fm
            break
    if acid_frag is None:
        return None
    rw = Chem.RWMol(acid_frag)
    for dummy in sorted(
        (a.GetIdx() for a in rw.GetAtoms() if a.GetAtomicNum() == 0), reverse=True
    ):
        rw.RemoveAtom(dummy)  # the ester-O relaxes to the acid -OH after sanitize
    try:
        Chem.SanitizeMol(rw)
        acid = Chem.RemoveHs(rw)
        acid_canon = Chem.CanonSmiles(Chem.MolToSmiles(acid))
    except Exception:
        return None
    from orthonym import name_compound  # lazy: data -> namer is acyclic at runtime
    acid_name = name_compound(acid_canon)
    if not acid_name or "unknown" in acid_name:
        return None
    if acid_name.endswith("oic acid"):
        return acid_name[: -len("oic acid")] + "oate"
    if acid_name.endswith("ic acid"):
        return acid_name[: -len("ic acid")] + "ate"
    return None


def _name_sugar_acyl_ester(mol) -> Optional[str]:
    """Free-sugar O-acyl ester -> functional-class ester name
    (``beta-D-glucopyranose 6-benzoate``, ``beta-D-glucopyranose
    2,3,4,6-tetraacetate``; BB P-102.5.6.1.1).  All acyls must be identical (the
    functional-class ester form multiplies one acylate word); mixed acyls (the
    ``x-O-acetyl-y-O-benzoyl`` prefix form) and anomeric O-acyl -> fail-closed.
    OPSIN-RT gated; the input mol is never mutated."""
    acyls = _find_sugar_acyl_esters(mol)
    if not acyls:
        return None
    words = []
    for (sugar_c, ester_o, acyl_c, _loc) in acyls:
        w = _acyl_to_ate_word(mol, acyl_c, ester_o, sugar_c)
        if w is None:
            return None
        words.append(w)
    if len(set(words)) != 1:
        return None  # mixed acyl -> fail-closed (O-acyl-prefix form deferred)
    word = words[0]
    locs = sorted(t[3] for t in acyls)

    # Strip every acyl ester: cleave each ester_o—acyl_c bond, keep the sugar side
    # (each ester-O relaxes to -OH), then name the residual free sugar.
    bond_idxs = []
    for (_sc, ester_o, acyl_c, _loc) in acyls:
        b = mol.GetBondBetweenAtoms(ester_o, acyl_c)
        if b is None:
            return None
        bond_idxs.append(b.GetIdx())
    try:
        frag = Chem.FragmentOnBonds(mol, bond_idxs, addDummies=True)
        mapping = []
        frags = Chem.GetMolFrags(
            frag, asMols=True, sanitizeFrags=False, fragsMolAtomMapping=mapping
        )
    except Exception:
        return None
    any_ester_o = acyls[0][1]
    sugar_frag = None
    for fm, mp in zip(frags, mapping):
        if any_ester_o in mp:
            sugar_frag = fm
            break
    if sugar_frag is None:
        return None
    rw = Chem.RWMol(sugar_frag)
    for dummy in sorted(
        (a.GetIdx() for a in rw.GetAtoms() if a.GetAtomicNum() == 0), reverse=True
    ):
        rw.RemoveAtom(dummy)
    try:
        Chem.SanitizeMol(rw)
        residual = Chem.RemoveHs(rw)
        residual_canon = Chem.CanonSmiles(Chem.MolToSmiles(residual))
    except Exception:
        return None
    residual_mol = Chem.MolFromSmiles(residual_canon)
    if residual_mol is None:
        return None
    sugar_name = name_free_sugar(residual_mol, residual_canon)
    if sugar_name is None:
        return None

    n = len(acyls)
    mult = _OMETHYL_MULT.get(n)
    if mult is None:
        return None
    # P-16.3.4: a complex acylate word (carrying a locant/space) takes the
    # bis/tris multiplier and enclosing marks; a simple word (acetate) does not.
    if n > 1 and any(ch in word for ch in "- ("):
        _BIS = {2: "bis", 3: "tris", 4: "tetrakis", 5: "pentakis", 6: "hexakis"}
        mult = _BIS[n]
        ester_term = f"({word})"
    else:
        ester_term = word
    locant_str = ",".join(str(x) for x in locs)
    candidate = f"{sugar_name} {locant_str}-{mult}{ester_term}"
    if not _mono_name_rt_ok(mol, candidate):
        return None
    return candidate


def name_sugar_ester(mol, canonical_smiles: str) -> Optional[str]:
    """Free-sugar mono-phosphate / sulfate ester (BB P-102.5.6.1.2 / P-102.5.6.1.3).

    The sugar is the parent; the ester is cited after the sugar name with its
    locant: ``D-glucopyranose 6-(dihydrogen phosphate)`` (BB 53209),
    ``alpha-D-glucopyranose 2-sulfate`` (ionized) / ``2-(hydrogen sulfate)``
    (acid, BB 53231), ``alpha-D-glucopyranose 1-phosphate`` (ionized glycosyl
    phosphate) / ``1-(dihydrogen phosphate)`` (acid, BB 53213).  The
    protonation-state word is derived IN PLACE from the acid centre (never
    neutralize-then-rename), reusing the class-agnostic
    :mod:`~orthonym.rules.conjugate_controller` primitives.

    Multi-ester (W6B-T3, BB P-102.5.6.1.2): 2-3 mono-phosphate esters of one
    sugar -> ``D-fructofuranose 1,6-bis(dihydrogen phosphate)`` (bis/tris, the
    P-16.3.4 complex multiplier since the ester word carries a space).

    Fail-closed (accuracy-first) on: >3 esters, a di/tri-phosphate or P-O-P bridge
    (183/184 territory), mixed protonation states, any non-sugar-ring molecule, or
    a residual the free-sugar namer cannot name.  Every emitted name is
    OPSIN-round-trip gated (:func:`_mono_name_rt_ok`) so a wrong locant/anomer
    cascade-continues rather than shipping.  The input mol is never mutated.
    """
    found = _find_sugar_oxoacid_ester(mol)
    if found is None:
        # W6B-T2: not a phosphate/sulfate ester -> try a free-sugar O-acyl ester.
        return _name_sugar_acyl_ester(mol)
    # `found` is a list of (sugar_c, ester_o, central, locant, word); 1-3 esters.
    words = [t[4] for t in found]
    if len(set(words)) != 1:
        return None  # mixed protonation state -> fail-closed
    word = words[0]
    locs = sorted(t[3] for t in found)

    # Strip every ester group: cleave each ester-O — P/S bond, keep the sugar-side
    # fragment (each ester-O relaxes to -OH), canonicalize.
    bond_idxs = []
    for (_sc, ester_o, central, _loc, _w) in found:
        bond = mol.GetBondBetweenAtoms(ester_o, central)
        if bond is None:
            return None
        bond_idxs.append(bond.GetIdx())
    try:
        frag = Chem.FragmentOnBonds(mol, bond_idxs, addDummies=True)
        mapping = []
        frags = Chem.GetMolFrags(
            frag, asMols=True, sanitizeFrags=False, fragsMolAtomMapping=mapping
        )
    except Exception:
        return None
    any_ester_o = found[0][1]
    sugar_frag = None
    for fm, mp in zip(frags, mapping):
        if any_ester_o in mp:
            sugar_frag = fm
            break
    if sugar_frag is None:
        return None
    rw = Chem.RWMol(sugar_frag)
    for dummy in sorted(
        (a.GetIdx() for a in rw.GetAtoms() if a.GetAtomicNum() == 0), reverse=True
    ):
        rw.RemoveAtom(dummy)  # each ester-O relaxes to -OH after sanitize
    try:
        Chem.SanitizeMol(rw)
        residual = Chem.RemoveHs(rw)
        residual_canon = Chem.CanonSmiles(Chem.MolToSmiles(residual))
    except Exception:
        return None
    residual_mol = Chem.MolFromSmiles(residual_canon)
    if residual_mol is None:
        return None

    sugar_name = name_free_sugar(residual_mol, residual_canon)
    if sugar_name is None:
        return None

    n = len(found)
    if n == 1:
        ester_term = f"({word})" if " " in word else word
        candidate = f"{sugar_name} {locs[0]}-{ester_term}"
    else:
        # P-16.3.4: a word carrying a space/locant takes bis/tris + enclosing
        # marks; a simple word (ionized 'sulfate') takes di/tri.
        if any(ch in word for ch in " -("):
            mult = {2: "bis", 3: "tris"}.get(n)
            ester_term = f"({word})"
        else:
            mult = {2: "di", 3: "tri"}.get(n)
            ester_term = word
        if mult is None:
            return None
        candidate = f"{sugar_name} {','.join(str(x) for x in locs)}-{mult}{ester_term}"
    if not _mono_name_rt_ok(mol, candidate):
        return None
    return candidate


def name_aldonate_ester(mol, canonical_smiles: str) -> Optional[str]:
    """Open-chain ALDONATE ester (BB P-102.5.6.6.2.1): the C1-COOH of an open-chain
    aldonic acid is esterified -> ``<R> <config>-<stem>onate``
    (``propan-2-yl D-gluconate``).

    Strip-and-name: the alkyl (R) group is named via the ester machinery
    (:func:`~orthonym.rules.esters.get_alkyl_fragment_name`); the residual free
    sugar-acid must be a RECOGNIZED aldonic acid (:func:`name_free_sugar`), else
    fail-closed.  OPSIN-RT gated; input mol never mutated.

    The aldarate PARTIAL ester (P-102.5.6.6.5.3) is DEFERRED fail-closed: the
    residual free diacid canonicalizes identically regardless of which terminus
    bore the ester, so the esterified-terminus locant/config cannot be derived
    without shipping a wrong name for the opposite-terminus isomer.
    """
    if mol is None:
        return None
    # Locate ester group(s): ester O (no H, degree 2) between a carbonyl C and an
    # alkyl C.
    esters = []  # (carbonyl_c, carbonyl_o, ester_o, alkyl_c)
    for atom in mol.GetAtoms():
        if atom.GetAtomicNum() != 8 or atom.GetTotalNumHs() > 0:
            continue
        nbrs = list(atom.GetNeighbors())
        if len(nbrs) != 2:
            continue
        carbonyl_c = carbonyl_o = alkyl_c = None
        for n in nbrs:
            if n.GetAtomicNum() != 6:
                continue
            dO = [b.GetOtherAtom(n).GetIdx() for b in n.GetBonds()
                  if b.GetBondType() == Chem.BondType.DOUBLE
                  and b.GetOtherAtom(n).GetAtomicNum() == 8]
            if dO:
                carbonyl_c, carbonyl_o = n.GetIdx(), dO[0]
            else:
                alkyl_c = n.GetIdx()
        if carbonyl_c is not None and alkyl_c is not None:
            esters.append((carbonyl_c, carbonyl_o, atom.GetIdx(), alkyl_c))
    if len(esters) != 1:
        return None
    carbonyl_c, carbonyl_o, ester_o, alkyl_c = esters[0]
    if mol.GetAtomWithIdx(carbonyl_c).IsInRing():
        return None  # sugar-acid backbone must be acyclic

    from orthonym.rules.esters import parse_ester_fragments, get_alkyl_fragment_name
    _acid_atoms, alkyl_atoms = parse_ester_fragments(
        mol, (carbonyl_c, carbonyl_o, ester_o, alkyl_c)
    )
    if not alkyl_atoms:
        return None
    alkyl_name = get_alkyl_fragment_name(mol, alkyl_atoms)
    if not alkyl_name:
        return None

    # Count free carboxylic acids (C(=O)-OH) in the input: 0 -> aldonate,
    # 1 -> aldarate partial ester; anything else -> fail-closed.
    free_cooh = 0
    for a in mol.GetAtoms():
        if a.GetAtomicNum() != 6:
            continue
        has_dO = any(b.GetBondType() == Chem.BondType.DOUBLE
                     and b.GetOtherAtom(a).GetAtomicNum() == 8 for b in a.GetBonds())
        has_ohO = any(nb.GetAtomicNum() == 8 and nb.GetTotalNumHs() > 0
                      for nb in a.GetNeighbors())
        if has_dO and has_ohO:
            free_cooh += 1
    if free_cooh not in (0, 1):
        return None

    # Strip the ester -> free acid: cleave ester_o — alkyl_c, keep the carbonyl side
    # (its ester-O relaxes to the acid -OH), canonicalize.
    bond = mol.GetBondBetweenAtoms(ester_o, alkyl_c)
    if bond is None:
        return None
    try:
        frag = Chem.FragmentOnBonds(
            mol, [bond.GetIdx()], addDummies=True, dummyLabels=[(0, 0)]
        )
        mapping = []
        frags = Chem.GetMolFrags(
            frag, asMols=True, sanitizeFrags=False, fragsMolAtomMapping=mapping
        )
    except Exception:
        return None
    acid_frag = None
    for fm, mp in zip(frags, mapping):
        if carbonyl_c in mp:
            acid_frag = fm
            break
    if acid_frag is None:
        return None
    rw = Chem.RWMol(acid_frag)
    for dummy in sorted(
        (a.GetIdx() for a in rw.GetAtoms() if a.GetAtomicNum() == 0), reverse=True
    ):
        rw.RemoveAtom(dummy)  # the ester-O relaxes to the acid -OH after sanitize
    try:
        Chem.SanitizeMol(rw)
        residual = Chem.RemoveHs(rw)
        residual_canon = Chem.CanonSmiles(Chem.MolToSmiles(residual))
    except Exception:
        return None
    residual_mol = Chem.MolFromSmiles(residual_canon)
    if residual_mol is None:
        return None
    acid_name = name_free_sugar(residual_mol, residual_canon)
    if acid_name is None:
        return None

    # W8-P7b.3: aldarate PARTIAL (mono) ester (P-102.5.6.6.5.3), free_cooh==1.
    # `<n>-<alkyl> hydrogen <config>-<stem>arate`. The 1-vs-6 ester locant labels
    # two DISTINCT isomers (L-altraric is not palindromic; BB gives both 1-methyl
    # and 6-methyl hydrogen L-altrarate), so the residual free diacid alone cannot
    # fix it. Resolve by a HARD OPSIN round-trip of each candidate against the
    # input — opsin_parse fails-CLOSED (returns None) without Java, so a genuinely
    # unverifiable input falls through to the systematic name (never a wrong
    # locant). meso aldarics are not cataloged (name_free_sugar -> None) -> already
    # fail-closed above. Prefer the lowest ester locant (1 before 6).
    if free_cooh == 1:
        if not acid_name.endswith("aric acid"):
            return None
        arate = acid_name[: -len("ic acid")] + "ate"  # L-altraric acid -> L-altrarate
        from ..validation.opsin_roundtrip import opsin_parse
        target = Chem.MolToSmiles(mol)
        for locant in (1, 6):
            cand = f"{locant}-{alkyl_name} hydrogen {arate}"
            parsed = opsin_parse(cand)
            if parsed:
                pm = Chem.MolFromSmiles(parsed)
                if pm is not None and Chem.MolToSmiles(pm) == target:
                    return cand
        return None  # unverifiable / no match -> fail closed (systematic)
    # Aldonate (single-carboxyl) ester: its single COOH is C1, no locant ambiguity.
    if free_cooh != 0:
        return None
    if not acid_name.endswith("onic acid"):
        return None
    acylate = acid_name[: -len("ic acid")] + "ate"  # ...onic acid -> ...onate
    candidate = f"{alkyl_name} {acylate}"
    if not _mono_name_rt_ok(mol, candidate):
        return None
    return candidate


def _glyco_ring_atoms(mol):
    """Return the atom-index set of a single pyranose/furanose sugar ring (exactly
    one ring O, the rest ring C, most ring C bearing an exocyclic O), else None."""
    ri = mol.GetRingInfo()
    for ring in ri.AtomRings():
        if len(ring) not in (5, 6):
            continue
        os_ = [i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O"]
        cs_ = [i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "C"]
        if len(os_) != 1 or len(cs_) != len(ring) - 1:
            continue
        o_bearing = sum(
            1 for c in cs_ if any(
                nb.GetSymbol() == "O" and nb.GetIdx() not in ring
                for nb in mol.GetAtomWithIdx(c).GetNeighbors()))
        if o_bearing >= len(cs_) - 1:
            return set(ring)
    return None


def name_glycosyloxy_yl_parent(mol, canonical_smiles: str) -> Optional[str]:
    """Glycosyloxy ``n-O-yl`` substituent on a senior parent (BB P-102.6.2).

    A monosaccharide bonded through a **non-anomeric** ring-position oxygen to a
    senior parent (e.g. acetic acid) is cited as the substituent
    ``<anomer>-<config>-glycopyranos-<n>-O-yl`` (the locant distinguishes it from
    the C-1 ``glycosyl``); the parent bears the principal characteristic group and
    is named normally -> ``(beta-D-glucopyranos-2-O-yl)acetic acid``.

    Deterministic + fail-closed: recognise a single clean sugar ring + a non-anomeric
    exocyclic ether O to a non-ring parent carbon; reconstruct the free sugar
    (ether O -> OH) via ``lookup_sugar``/``recognize_sugar_skeleton``; name the
    parent fragment via a gate-off inner namer; then pick the ``n-O-yl`` LOCANT by
    a HARD OPSIN round-trip of each candidate against the input (``opsin_parse``
    fails-CLOSED without Java). Any miss -> ``None`` (cascade-continue). Never
    mutates the input mol.
    """
    if mol is None:
        return None
    ring = _glyco_ring_atoms(mol)
    if ring is None:
        return None
    ring_o = next(i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O")
    anomeric = None
    for c in ring:
        a = mol.GetAtomWithIdx(c)
        if a.GetSymbol() != "C":
            continue
        nb_idx = [n.GetIdx() for n in a.GetNeighbors()]
        if ring_o in nb_idx and any(
                nb.GetSymbol() == "O" and nb.GetIdx() not in ring
                for nb in a.GetNeighbors()):
            anomeric = c
            break
    # single non-anomeric ring-O ether to a non-ring parent carbon
    links = []
    for a in mol.GetAtoms():
        if a.GetSymbol() != "O" or a.GetTotalNumHs() > 0 or a.GetDegree() != 2:
            continue
        rc = [n.GetIdx() for n in a.GetNeighbors() if n.GetIdx() in ring]
        pc = [n.GetIdx() for n in a.GetNeighbors()
              if n.GetIdx() not in ring and n.GetSymbol() == "C"]
        if len(rc) == 1 and len(pc) == 1 and rc[0] != anomeric:
            links.append((a.GetIdx(), rc[0], pc[0]))
    if len(links) != 1:
        return None
    link_o, ring_c, parent_c = links[0]

    rw = Chem.RWMol(mol)
    rw.RemoveBond(parent_c, link_o)
    frags = Chem.GetMolFrags(rw, asMols=False)
    sugar_atoms = next((set(f) for f in frags if ring_o in f), None)
    parent_atoms = next((set(f) for f in frags if parent_c in f), None)
    if sugar_atoms is None or parent_atoms is None or link_o not in sugar_atoms:
        return None

    def _submol(atomset):
        bidx = [b.GetIdx() for b in rw.GetBonds()
                if b.GetBeginAtomIdx() in atomset and b.GetEndAtomIdx() in atomset]
        sm = Chem.PathToSubmol(rw, bidx)
        try:
            Chem.SanitizeMol(sm)
        except Exception:
            return None
        return sm

    sugar_mol = _submol(sugar_atoms)
    parent_mol = _submol(parent_atoms)
    if sugar_mol is None or parent_mol is None:
        return None
    sugar_can = Chem.MolToSmiles(sugar_mol)
    info = lookup_sugar(sugar_can) or recognize_sugar_skeleton(
        Chem.MolFromSmiles(sugar_can))
    if info is None:
        return None
    anomer, config, base = info
    if not (anomer and config and base.endswith("ose")):
        return None

    from orthonym.namer import Orthonym
    parent_name = Orthonym(_disable_opsin_validity_gate=True).name(
        Chem.MolToSmiles(parent_mol))
    if not parent_name or parent_name == "unknown organic compound":
        return None

    from ..validation.opsin_roundtrip import opsin_parse
    stem = base[:-1]  # glucopyranose -> glucopyranos
    target = Chem.MolToSmiles(mol)
    for n in (2, 3, 4, 5, 6):
        cand = f"({anomer}-{config}-{stem}-{n}-O-yl){parent_name}"
        parsed = opsin_parse(cand)
        if parsed:
            pm = Chem.MolFromSmiles(parsed)
            if pm is not None and Chem.MolToSmiles(pm) == target:
                return cand
    return None


_C_SUGAR_HALO = {9: "fluoro", 17: "chloro", 35: "bromo", 53: "iodo"}


def _c_sugar_ring(mol):
    """A single 5-/6-membered ring with exactly one ring O and the rest C
    (loose sugar-ring gate; downstream lookup + RT verify supply the safety)."""
    for ring in mol.GetRingInfo().AtomRings():
        if len(ring) not in (5, 6):
            continue
        os_ = [i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O"]
        cs_ = [i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "C"]
        if len(os_) == 1 and len(cs_) == len(ring) - 1:
            return set(ring)
    return None


def _c_sub_name(mol, sub_atoms, attach):
    """Name the exocyclic C-substituent (halogen / alkyl / phenyl), else None."""
    if len(sub_atoms) == 1:
        a = mol.GetAtomWithIdx(next(iter(sub_atoms)))
        if a.GetAtomicNum() in _C_SUGAR_HALO:
            return _C_SUGAR_HALO[a.GetAtomicNum()]
    atoms = [mol.GetAtomWithIdx(i) for i in sub_atoms]
    if all(a.GetAtomicNum() == 6 for a in atoms):
        if len(sub_atoms) == 6 and all(a.GetIsAromatic() for a in atoms):
            return "phenyl"
        from orthonym.rules.esters import get_alkyl_fragment_name
        return get_alkyl_fragment_name(mol, list(sub_atoms)) or None
    return None


def _is_c_substituted_sugar_shape(mol) -> bool:
    """Cheap NO-OPSIN pre-gate for the dispatch predicate: a single 5-/6-membered
    one-O ring with EXACTLY one non-terminal ring carbon bearing an exocyclic C or
    halogen substituent (beyond the sugar's own terminal CH2OH/CHO). The handler
    (:func:`name_c_substituted_sugar`) does the real reconstruction + RT gate."""
    if mol is None:
        return False
    ring = _c_sugar_ring(mol)
    if ring is None:
        return False
    hits = 0
    for c in ring:
        a = mol.GetAtomWithIdx(c)
        if a.GetSymbol() != "C":
            continue
        for nb in a.GetNeighbors():
            if nb.GetIdx() in ring or nb.GetAtomicNum() == 8:
                continue
            if nb.GetAtomicNum() == 6:
                heavy = [x for x in nb.GetNeighbors()
                         if x.GetAtomicNum() > 1 and x.GetIdx() != c]
                if len(heavy) == 1 and heavy[0].GetAtomicNum() == 8:
                    continue
            hits += 1
    return hits == 1


def name_c_substituted_sugar(mol, canonical_smiles: str) -> Optional[str]:
    """C-substituted monosaccharide (BB P-102.5.6.3.1/.3.2).

    A non-terminal ring carbon bearing an extra C-substituent (or a halogen):
      * keeps its OH -> ``<n>-C-<substituent>-<sugar>`` (P-102.5.6.3.1);
      * lost its OH -> ``<n>-deoxy-<n>-<substituent>-<sugar>`` (P-102.5.6.3.2).

    The substituted centre's config is NOT structurally recoverable (the group
    replaced/added at the OH position), so the parent aldose is reconstructed with
    that ONE centre left unassigned, both epimers are enumerated, and the correct
    ``(anomer, config, base)`` + LOCANT is fixed by a HARD OPSIN round-trip of each
    candidate against the input (``opsin_parse`` fails-CLOSED without Java). Any
    miss -> ``None`` (cascade-continue). Input mol never mutated.
    """
    if mol is None:
        return None
    ring = _c_sugar_ring(mol)
    if ring is None:
        return None
    hits = []
    for c in ring:
        a = mol.GetAtomWithIdx(c)
        if a.GetSymbol() != "C":
            continue
        for nb in a.GetNeighbors():
            if nb.GetIdx() in ring or nb.GetAtomicNum() == 8:
                continue
            if nb.GetAtomicNum() == 6:
                heavy = [x for x in nb.GetNeighbors()
                         if x.GetAtomicNum() > 1 and x.GetIdx() != c]
                if len(heavy) == 1 and heavy[0].GetAtomicNum() == 8:
                    continue  # the sugar's own terminal CH2OH / CHO
            hits.append((c, nb.GetIdx()))
    if len(hits) != 1:
        return None
    ring_c, sub_start = hits[0]
    has_oh = any(nb.GetAtomicNum() == 8 and nb.GetTotalNumHs() > 0
                 for nb in mol.GetAtomWithIdx(ring_c).GetNeighbors())

    from collections import deque as _deque
    seen = {sub_start}
    q = _deque([sub_start])
    while q:
        cur = q.popleft()
        for nb in mol.GetAtomWithIdx(cur).GetNeighbors():
            if nb.GetIdx() != ring_c and nb.GetIdx() not in seen:
                seen.add(nb.GetIdx())
                q.append(nb.GetIdx())
    sub_name = _c_sub_name(mol, seen, ring_c)
    if sub_name is None:
        return None

    rw = Chem.RWMol(mol)
    for idx in sorted(seen, reverse=True):
        rw.RemoveAtom(idx)
    rc = ring_c - sum(1 for i in seen if i < ring_c)
    if not has_oh:  # deoxy-C: restore an OH where the substituent replaced it
        newo = rw.AddAtom(Chem.Atom(8))
        rw.AddBond(rc, newo, Chem.BondType.SINGLE)
    rc_atom = rw.GetAtomWithIdx(rc)
    rc_atom.SetChiralTag(Chem.ChiralType.CHI_UNSPECIFIED)
    rc_atom.SetNoImplicit(False)
    rc_atom.SetNumExplicitHs(0)
    try:
        rc_atom.UpdatePropertyCache()
        Chem.SanitizeMol(rw)
    except Exception:
        return None
    from rdkit.Chem.EnumerateStereoisomers import (
        EnumerateStereoisomers, StereoEnumerationOptions)
    parent_infos = set()
    for iso in EnumerateStereoisomers(
            rw, options=StereoEnumerationOptions(onlyUnassigned=True)):
        try:
            pc = Chem.MolToSmiles(iso)
        except Exception:
            continue
        info = lookup_sugar(pc) or recognize_sugar_skeleton(Chem.MolFromSmiles(pc))
        if info and info[0] and info[1] and info[2].endswith("ose"):
            parent_infos.add(info)
    if not parent_infos:
        return None

    from ..validation.opsin_roundtrip import opsin_parse
    target = Chem.MolToSmiles(mol)
    for anomer, config, base in sorted(parent_infos):
        for n in range(2, len(ring) + 1):
            cand = (f"{n}-C-{sub_name}-{anomer}-{config}-{base}" if has_oh
                    else f"{n}-deoxy-{n}-{sub_name}-{anomer}-{config}-{base}")
            parsed = opsin_parse(cand)
            if parsed:
                pm = Chem.MolFromSmiles(parsed)
                if pm is not None and Chem.MolToSmiles(pm) == target:
                    return cand
    return None


def _has_open_chain_acid_ester(mol) -> bool:
    """Cheap NO-OPSIN detector (W6B-T8) for a candidate aldonate/aldarate ester: a
    fully acyclic molecule with exactly one -C(=O)-O-C ester and >=2 hydroxylated
    carbons (a polyol acid chain).  Safe for the dispatch predicate; the handler
    (:func:`name_aldonate_ester`) does the real name_free_sugar + RT validation and
    fails closed on a non-sugar-acid residual."""
    if mol is None or mol.GetRingInfo().NumRings() > 0:
        return False
    n_ester = 0
    for atom in mol.GetAtoms():
        if atom.GetAtomicNum() != 8 or atom.GetTotalNumHs() > 0:
            continue
        nbrs = list(atom.GetNeighbors())
        if len(nbrs) != 2:
            continue
        cc = ac = None
        for n in nbrs:
            if n.GetAtomicNum() != 6:
                continue
            if any(b.GetBondType() == Chem.BondType.DOUBLE
                   and b.GetOtherAtom(n).GetAtomicNum() == 8 for b in n.GetBonds()):
                cc = n.GetIdx()
            else:
                ac = n.GetIdx()
        if cc is not None and ac is not None:
            n_ester += 1
    if n_ester != 1:
        return False
    oh_c = sum(
        1 for a in mol.GetAtoms()
        if a.GetAtomicNum() == 6
        and any(nb.GetAtomicNum() == 8 and nb.GetTotalNumHs() > 0
                for nb in a.GetNeighbors())
    )
    return oh_c >= 2


def name_amino_deoxy_open_sugar(mol, canonical_smiles: str) -> Optional[str]:
    """N-alkylamino open-chain aldose (BB P-102.5.4.1.2): a backbone carbon of an
    open-chain aldose bears -N(H)R (R = alkyl) in place of -OH ->
    ``<n>-(<R>amino)-<n>-deoxy-<config>-<stem>`` (``2-(butylamino)-2-deoxy-D-glucose``).

    Strip-and-name: replace the N (and its R group) with -OH IN PLACE (preserving
    the backbone stereo tag), name the parent aldose via :func:`name_free_sugar`,
    and cite the N-substituent.  OPSIN-RT gated.  Fail-closed on a ring form,
    N-acyl / N-hydroxyalkyl (R carries O), or more than one amino carbon.
    """
    if mol is None or mol.GetRingInfo().NumRings() > 0:
        return None
    from orthonym.rules.esters import get_alkyl_fragment_name, _bfs_fragment

    # C1 = the terminal aldehyde carbon (CHO): acyclic C, one =O (terminal), one C
    # neighbour, >=1 H.
    aldehyde = None
    for a in mol.GetAtoms():
        if a.GetAtomicNum() != 6:
            continue
        dO = [b.GetOtherAtom(a) for b in a.GetBonds()
              if b.GetBondType() == Chem.BondType.DOUBLE
              and b.GetOtherAtom(a).GetAtomicNum() == 8]
        cN = [nb for nb in a.GetNeighbors() if nb.GetAtomicNum() == 6]
        if len(dO) == 1 and len(cN) == 1 and a.GetTotalNumHs() >= 1 \
                and dO[0].GetDegree() == 1:
            if aldehyde is not None:
                return None  # >1 aldehyde -> not a simple aldose
            aldehyde = a.GetIdx()
    if aldehyde is None:
        return None

    # Walk the carbon backbone from C1 -> locant map.
    order = [aldehyde]
    prev, cur = None, aldehyde
    while True:
        nxts = [nb.GetIdx() for nb in mol.GetAtomWithIdx(cur).GetNeighbors()
                if nb.GetAtomicNum() == 6 and nb.GetIdx() != prev]
        if len(nxts) != 1:
            break
        prev, cur = cur, nxts[0]
        order.append(cur)
    locant_of = {c: i + 1 for i, c in enumerate(order)}

    # Exactly one backbone carbon bears an amine N (N-H, acyclic): primary (-NH2,
    # 1 carbon neighbour = the backbone) or secondary alkyl (-NHR, 2 carbons).
    amino_c = n_idx = r_c = None
    for c in order:
        for nb in mol.GetAtomWithIdx(c).GetNeighbors():
            if nb.GetAtomicNum() == 7 and not nb.IsInRing() and nb.GetTotalNumHs() >= 1:
                cnbrs = [x.GetIdx() for x in nb.GetNeighbors() if x.GetAtomicNum() == 6]
                if len(cnbrs) not in (1, 2):
                    return None
                if amino_c is not None:
                    return None  # >1 amino carbon -> fail-closed
                amino_c, n_idx = c, nb.GetIdx()
                r_c = next((x for x in cnbrs if x != c), None)  # None = primary
    if amino_c is None:
        return None

    # Build the N-substituent citation and collect the R atoms to strip.
    if r_c is None:
        substituent = "amino"  # primary -NH2
        r_atoms = []
    else:
        # R must be a pure-carbon (alkyl) group: an N-acyl / N-hydroxyalkyl would
        # drop its O on the strip -> fail-closed.
        r_atoms = _bfs_fragment(mol, r_c, n_idx)
        if any(mol.GetAtomWithIdx(i).GetAtomicNum() != 6 for i in r_atoms):
            return None
        r_name = get_alkyl_fragment_name(mol, r_atoms)
        if not r_name:
            return None
        substituent = f"({r_name}amino)"

    # Strip: N -> O in place (stereo tag preserved), delete the R atoms.
    rw = Chem.RWMol(mol)
    rw.GetAtomWithIdx(n_idx).SetAtomicNum(8)
    for idx in sorted(r_atoms, reverse=True):
        rw.RemoveAtom(idx)
    try:
        Chem.SanitizeMol(rw)
        parent = Chem.RemoveHs(rw)
        parent_canon = Chem.CanonSmiles(Chem.MolToSmiles(parent))
    except Exception:
        return None
    parent_mol = Chem.MolFromSmiles(parent_canon)
    if parent_mol is None:
        return None
    aldose_name = name_free_sugar(parent_mol, parent_canon)
    if aldose_name is None:
        return None
    # Parent must be a plain open-chain aldose ('<config>-<stem>ose').
    if " " in aldose_name or "acid" in aldose_name or not aldose_name.endswith("ose"):
        return None

    loc = locant_of[amino_c]
    candidate = f"{loc}-{substituent}-{loc}-deoxy-{aldose_name}"
    if not _mono_name_rt_ok(mol, candidate):
        return None
    return candidate


_GLYCOSYLOXY_SENIOR_SUFFIXES = (
    "one", "al", "oic acid", "amide", "nitrile", "carbaldehyde",
    "carboxylic acid", "carbonitrile", "imine", "oyl chloride", "oyl bromide",
)


def _escalate_enclosing_marks(name: str, token: str, replacement: str) -> Optional[str]:
    """Replace the single WHOLE-WORD ``token`` inside its enclosing ``(...)`` group
    with ``replacement`` (which itself carries parentheses), and escalate that
    group's delimiters from ``(...)`` to ``[...]`` (P-16.3.3 nesting).  Returns the
    rebuilt name, or ``None`` if ``token`` is absent/ambiguous or unenclosed.

    LEFT-boundary match is essential: a substituent token concatenates onto its
    parent with no space (``methoxyphenyl``), so a right boundary would fail; but a
    native aglycone methoxy merges with the placeholder under a ``di``/``tri``
    multiplier (``dimethoxy``), where the token is preceded by a LETTER — so
    requiring a non-letter to the LEFT excludes the merged form and any second
    (non-merged / ``methoxycarbonyl``) occurrence pushes the count off 1, failing
    closed rather than corrupting a multiplied prefix (review W6B finding)."""
    pat = re.compile(r'(?<![A-Za-z])' + re.escape(token))
    if len(pat.findall(name)) != 1:
        return None
    i = pat.search(name).start()
    depth = 0
    open_i = None
    for j in range(i - 1, -1, -1):
        if name[j] == ")":
            depth += 1
        elif name[j] == "(":
            if depth == 0:
                open_i = j
                break
            depth -= 1
    if open_i is None:
        return None
    depth = 0
    close_i = None
    for j in range(i + len(token), len(name)):
        if name[j] == "(":
            depth += 1
        elif name[j] == ")":
            if depth == 0:
                close_i = j
                break
            depth -= 1
    if close_i is None:
        return None
    inner = pat.sub(replacement, name[open_i + 1:close_i])
    return name[:open_i] + "[" + inner + "]" + name[close_i + 1:]


def name_glycosyloxy_aglycone(mol, canonical_smiles: str) -> Optional[str]:
    """Glycosyloxy on a senior aglycone (BB P-102.6.1.2): a sugar O-glycosidically
    bonded to an aglycone that bears a characteristic group SENIOR to hydroxy is
    named as a ``(<config>-glycosyloxy)`` substituent PREFIX on the aglycone parent
    (``1-[4-(beta-D-glucopyranosyloxy)phenyl]ethan-1-one``).

    Placeholder mechanism (root-cause, RT-gated): replace the sugar with a methyl
    (-> the aglycone methyl ether, which Orthonym names natively), require the
    aglycone to carry a senior-group suffix (else it is a simple glycoside ->
    fail-closed for the glycoside path), then swap the single ``methoxy`` token for
    ``(<glycosyloxy>)`` and escalate its enclosing marks (P-16.5.1.1).  Fail-closed on
    >1 sugar ring, a free/undefined anomeric, a non-senior aglycone, or an RT-fail.
    """
    if mol is None:
        return None
    ri = mol.GetRingInfo()
    sugar_rings = [
        r for r in ri.AtomRings()
        if len(r) in (5, 6)
        and sum(1 for i in r if mol.GetAtomWithIdx(i).GetSymbol() == "O") == 1
        and all(mol.GetAtomWithIdx(i).GetSymbol() in ("C", "O") for i in r)
    ]
    if len(sugar_rings) != 1:
        return None  # 0 -> not a glycoside; >=2 -> disaccharide glycoside (elsewhere)
    ring = sugar_rings[0]
    ringset = set(ring)
    ro = next(i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O")
    anomeric_idx = anomeric_exo_o = None
    for idx in ring:
        a = mol.GetAtomWithIdx(idx)
        if a.GetSymbol() != "C" or not any(n.GetIdx() == ro for n in a.GetNeighbors()):
            continue
        exo = [n.GetIdx() for n in a.GetNeighbors()
               if n.GetIdx() not in ringset and n.GetSymbol() == "O"]
        if len(exo) == 1:
            anomeric_idx, anomeric_exo_o = idx, exo[0]
            break
    if anomeric_idx is None:
        return None
    o_atom = mol.GetAtomWithIdx(anomeric_exo_o)
    if o_atom.GetTotalNumHs() > 0:
        return None  # free anomeric -OH -> not a glycoside
    c_nbrs = [n.GetIdx() for n in o_atom.GetNeighbors() if n.GetAtomicNum() == 6]
    if len(c_nbrs) != 2:
        return None
    aglycone_c = next((c for c in c_nbrs if c != anomeric_idx), None)
    if aglycone_c is None:
        return None

    # Recognize the sugar -> glycosyloxy prefix.
    from orthonym.rules.conjugate_controller import _extract_capped_sugar
    sugar_canon = _extract_capped_sugar(mol, anomeric_idx, anomeric_exo_o)
    if not sugar_canon:
        return None
    sugar_mol = Chem.MolFromSmiles(sugar_canon)
    if sugar_mol is None:
        return None
    tup = lookup_sugar(Chem.MolToSmiles(sugar_mol)) or recognize_sugar_skeleton(sugar_mol)
    if tup is None:
        return None
    glycosyloxy = sugar_to_glycosyloxy_prefix(*tup)

    # Build the aglycone methyl ether: cleave anomeric-C — glycosidic-O, keep the
    # aglycone side, and cap the glycosidic O with a methyl.
    bond = mol.GetBondBetweenAtoms(anomeric_idx, anomeric_exo_o)
    if bond is None:
        return None
    try:
        frag = Chem.FragmentOnBonds(mol, [bond.GetIdx()], addDummies=True,
                                    dummyLabels=[(0, 0)])
        mapping: list = []
        frags = Chem.GetMolFrags(frag, asMols=True, sanitizeFrags=False,
                                 fragsMolAtomMapping=mapping)
    except Exception:
        return None
    aglycone_frag = None
    for fm, mp in zip(frags, mapping):
        if anomeric_exo_o in mp:
            aglycone_frag = fm
            break
    if aglycone_frag is None:
        return None
    rw = Chem.RWMol(aglycone_frag)
    for at in rw.GetAtoms():
        if at.GetAtomicNum() == 0:  # dummy where the sugar was -> methyl cap
            at.SetAtomicNum(6)
            at.SetNoImplicit(False)
            at.SetNumExplicitHs(3)
    try:
        Chem.SanitizeMol(rw)
        aglycone_ether = Chem.CanonSmiles(Chem.MolToSmiles(Chem.RemoveHs(rw)))
    except Exception:
        return None
    from orthonym import name_compound
    ether_name = name_compound(aglycone_ether)
    if not ether_name or "unknown" in ether_name:
        return None
    # The aglycone must bear a group SENIOR to hydroxy (else the glycoside
    # functional-class form is preferred -> defer to that path).
    if not any(ether_name.endswith(s) for s in _GLYCOSYLOXY_SENIOR_SUFFIXES):
        return None
    if "methoxy" not in ether_name:
        return None
    candidate = _escalate_enclosing_marks(ether_name, "methoxy", f"({glycosyloxy})")
    if candidate is None:
        return None
    if not _mono_name_rt_ok(mol, candidate):
        return None
    return candidate


def _is_sugar_o_ether_leak(mol) -> bool:
    """VETO (W6B-T13, accuracy-first): True for a sugar ring whose NON-anomeric
    ring carbon bears an -O-R ether where R is neither a bare methyl (O-methyl,
    named by :func:`name_sugar_o_methyl`) nor an acyl carbonyl (O-acyl ester,
    named by :func:`name_sugar_ester`) -- e.g. the n-O-yl shape
    (sugar-C-O-CH2-COOH).  The general chain namer drops the whole sugar for these
    (-> a wrong 'ethanoic acid' name), so the carbohydrate handler must fail closed
    instead.  Pure RDKit; NO OPSIN."""
    if mol is None:
        return False
    ri = mol.GetRingInfo()
    sugar_rings = [
        r for r in ri.AtomRings()
        if len(r) in (5, 6)
        and sum(1 for i in r if mol.GetAtomWithIdx(i).GetSymbol() == "O") == 1
        and all(mol.GetAtomWithIdx(i).GetSymbol() in ("C", "O") for i in r)
    ]
    if len(sugar_rings) != 1:
        return False
    ring = sugar_rings[0]
    ringset = set(ring)
    ro = next((i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O"), None)
    if ro is None:
        return False
    # locate the anomeric carbon (ring C bonded to ring-O + an exocyclic O).
    anomeric_idx = None
    for idx in ring:
        a = mol.GetAtomWithIdx(idx)
        if a.GetSymbol() != "C" or not any(n.GetIdx() == ro for n in a.GetNeighbors()):
            continue
        if any(n.GetIdx() not in ringset and n.GetAtomicNum() == 8 for n in a.GetNeighbors()):
            anomeric_idx = idx
            break
    for idx in ring:
        a = mol.GetAtomWithIdx(idx)
        if a.GetSymbol() != "C" or idx == anomeric_idx:
            continue
        for nb in a.GetNeighbors():
            if nb.GetIdx() in ringset or nb.GetAtomicNum() != 8 or nb.GetTotalNumHs() > 0:
                continue
            # an ether O on a non-anomeric ring carbon: find the far carbon R.
            r_c = next((x for x in nb.GetNeighbors()
                        if x.GetIdx() != idx and x.GetAtomicNum() == 6), None)
            if r_c is None:
                continue
            # bare methyl (O-methyl, handled) -> not a leak.
            if (r_c.GetDegree() == 1 and r_c.GetTotalNumHs() == 3):
                continue
            # acyl carbonyl (O-acyl ester, handled) -> not a leak.
            if any(b.GetBondType() == Chem.BondType.DOUBLE
                   and b.GetOtherAtom(r_c).GetAtomicNum() == 8 for b in r_c.GetBonds()):
                continue
            # SUGAR-NESS gate (review W6B finding): only veto when the ring is a
            # REAL sugar -- cap the ether (restore its -OH) and require the isolated
            # ring to recognize as a monosaccharide.  A plain (non-sugar)
            # tetrahydropyran/-furan ether is NOT vetoed (it stays nameable).
            from orthonym.rules.conjugate_controller import _extract_capped_sugar
            capped = _extract_capped_sugar(mol, idx, nb.GetIdx())
            if not capped:
                continue
            cap_mol = Chem.MolFromSmiles(capped)
            if cap_mol is None:
                continue
            if (lookup_sugar(Chem.MolToSmiles(cap_mol)) is not None
                    or recognize_sugar_skeleton(cap_mol) is not None
                    or name_monosaccharide_systematic(cap_mol) is not None):
                return True  # a real sugar with an O-ether the namers can't handle
    return False


def sugar_to_glycosyl_prefix(anomer: str, config: str, base_name: str) -> str:
    """Convert sugar info to a C-glycosyl substituent prefix (``-ose`` -> ``-osyl``,
    NO ``oxy``): ``sugar_to_glycosyl_prefix("beta","D","glucopyranose")`` ->
    ``'beta-D-glucopyranosyl'``."""
    if base_name.endswith("ose"):
        stem = base_name[:-1] + "yl"
    else:
        stem = base_name + "yl"
    if anomer and config:
        return f"{anomer}-{config}-{stem}"
    return stem


def name_c_glycosyl_aglycone(mol, canonical_smiles: str) -> Optional[str]:
    """C-glycosyl on a senior aglycone (BB P-102.6.1.4): a sugar bonded by a C-C
    bond from its anomeric carbon to an aglycone that is the parent ->
    ``n-(<config>-glycosyl)`` substituent prefix
    (``2-(beta-D-glucopyranosyl)benzene-1,3,5-triol``).

    Placeholder mechanism (RT-gated): cap the anomeric-C — aglycone-C bond to
    recognize the sugar, then replace the sugar with a methyl (-> the aglycone
    methyl-substituted parent, named natively), and swap the single ``methyl``
    token for ``(<glycosyl>)``.  Fail-closed on >1 sugar ring, an exocyclic-O
    anomeric (that is an O-glycoside, T12), an unrecognized sugar, or an RT-fail."""
    if mol is None:
        return None
    ri = mol.GetRingInfo()
    sugar_rings = [
        r for r in ri.AtomRings()
        if len(r) in (5, 6)
        and sum(1 for i in r if mol.GetAtomWithIdx(i).GetSymbol() == "O") == 1
        and all(mol.GetAtomWithIdx(i).GetSymbol() in ("C", "O") for i in r)
    ]
    if len(sugar_rings) != 1:
        return None
    ring = sugar_rings[0]
    ringset = set(ring)
    ro = next(i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == "O")
    from orthonym.rules.conjugate_controller import _extract_capped_sugar
    for idx in ring:
        a = mol.GetAtomWithIdx(idx)
        if a.GetSymbol() != "C" or not any(n.GetIdx() == ro for n in a.GetNeighbors()):
            continue
        exo_c = [n.GetIdx() for n in a.GetNeighbors()
                 if n.GetIdx() not in ringset and n.GetAtomicNum() == 6]
        exo_o = [n for n in a.GetNeighbors()
                 if n.GetIdx() not in ringset and n.GetAtomicNum() == 8]
        if len(exo_c) != 1 or exo_o:
            continue  # anomeric of a C-glycosyl: exactly one exocyclic C, NO exo O
        aglycone_c = exo_c[0]
        # The exocyclic carbon must NOT be a plain sugar CH2OH tail (that is C6).
        agl_atom = mol.GetAtomWithIdx(aglycone_c)
        if agl_atom.GetTotalNumHs() >= 2 and any(
            nb.GetAtomicNum() == 8 for nb in agl_atom.GetNeighbors()
        ):
            continue  # looks like the C6 CH2OH, not an aglycone
        sugar_canon = _extract_capped_sugar(mol, idx, aglycone_c)
        if not sugar_canon:
            continue
        sm = Chem.MolFromSmiles(sugar_canon)
        if sm is None:
            continue
        tup = lookup_sugar(Chem.MolToSmiles(sm)) or recognize_sugar_skeleton(sm)
        if tup is None:
            continue
        glycosyl = sugar_to_glycosyl_prefix(*tup)

        # Build the aglycone with a methyl in place of the sugar.
        bond = mol.GetBondBetweenAtoms(idx, aglycone_c)
        if bond is None:
            return None
        try:
            frag = Chem.FragmentOnBonds(mol, [bond.GetIdx()], addDummies=True,
                                        dummyLabels=[(0, 0)])
            mapping: list = []
            frags = Chem.GetMolFrags(frag, asMols=True, sanitizeFrags=False,
                                     fragsMolAtomMapping=mapping)
        except Exception:
            return None
        agl_frag = None
        for fm, mp in zip(frags, mapping):
            if aglycone_c in mp:
                agl_frag = fm
                break
        if agl_frag is None:
            return None
        rw = Chem.RWMol(agl_frag)
        for at in rw.GetAtoms():
            if at.GetAtomicNum() == 0:  # dummy -> methyl
                at.SetAtomicNum(6)
                at.SetNoImplicit(False)
                at.SetNumExplicitHs(3)
        try:
            Chem.SanitizeMol(rw)
            agl_methyl = Chem.CanonSmiles(Chem.MolToSmiles(Chem.RemoveHs(rw)))
        except Exception:
            return None
        from orthonym import name_compound
        agl_name = name_compound(agl_methyl)
        if not agl_name or "unknown" in agl_name:
            return None
        # LEFT-boundary 'methyl' only: a substituent concatenates onto its parent
        # with no space ('methylbenzene'), so a right boundary would fail; but a
        # native aglycone methyl merges with the placeholder under a di/tri
        # multiplier ('dimethyl'), where 'methyl' is preceded by a LETTER -> the
        # left boundary excludes it, and any second occurrence ('methylene',
        # non-merged native) pushes the count off 1, failing closed (review W6B).
        pat = re.compile(r'(?<![A-Za-z])methyl')
        if len(pat.findall(agl_name)) != 1:
            return None
        candidate = pat.sub(f"({glycosyl})", agl_name, count=1)
        if not _mono_name_rt_ok(mol, candidate):
            return None
        return candidate
    return None


