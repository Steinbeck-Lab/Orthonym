def lookup_sugar(canonical_smiles: str) -> Optional[Tuple[str, str, str]]:
    """Look up a sugar retained name by canonical SMILES.

    First tries exact match (stereo-specific). If no match and the SMILES
    has no @ characters, falls back to connectivity-only matching which
    returns the base sugar name without anomer/config descriptors.

    Args:
        canonical_smiles: RDKit canonical SMILES of the sugar fragment.

    Returns:
        Tuple of (anomer, config, base_name) or None if not a known sugar.
        For non-stereo matches, anomer and config are empty strings.

    Examples:
        >>> lookup_sugar("OC[C@H]1O[C@@H](O)[C@H](O)[C@@H](O)[C@@H]1O")
        ('beta', 'D', 'glucopyranose')
        >>> lookup_sugar("OCC1OC(O)C(O)C(O)C1O")  # non-stereo
        ('', '', 'glucopyranose')
        >>> lookup_sugar("CCCC")
        None
    """
    # Try exact stereo match first
    result = ALL_SUGAR_NAMES.get(canonical_smiles)
    if result is not None:
        return result

    # If SMILES has no stereo, try non-stereo fallback
    if "@" not in canonical_smiles:
        return _NON_STEREO_SUGAR_FALLBACK.get(canonical_smiles)

    return None


def sugar_to_glycosyloxy_prefix(
    anomer: str, config: str, base_name: str
) -> str:
    """Convert sugar info to glycosyloxy prefix string.

    Transforms the base sugar name ending from "-ose" to "-osyloxy"
    and prepends anomer-config descriptors if present.

    Args:
        anomer: Anomeric descriptor ("alpha", "beta", or "").
        config: Configurational descriptor ("D", "L", or "").
        base_name: Sugar base name (e.g., "glucopyranose").

    Returns:
        Glycosyloxy prefix string.

    Examples:
        >>> sugar_to_glycosyloxy_prefix("beta", "D", "glucopyranose")
        'beta-D-glucopyranosyloxy'
        >>> sugar_to_glycosyloxy_prefix("alpha", "L", "rhamnopyranose")
        'alpha-L-rhamnopyranosyloxy'
        >>> sugar_to_glycosyloxy_prefix("", "", "glucopyranose")
        'glucopyranosyloxy'
    """
    # Convert -ose ending to -osyloxy
    # "glucopyranose" -> "glucopyranosyl" -> "glucopyranosyloxy"
    # Works for all sugar names including modified ones like
    # "2-(acetylamino)-2-deoxy-glucopyranose"
    if base_name.endswith("ose"):
        stem = base_name[:-1] + "yl"  # -ose -> -osyl
    else:
        stem = base_name + "yl"

    glycosyloxy = stem + "oxy"

    # Build prefix with descriptors
    if anomer and config:
        return f"{anomer}-{config}-{glycosyloxy}"
    else:
        return glycosyloxy
