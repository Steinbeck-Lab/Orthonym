OPSIN_SUGAR_NAMES: Dict[str, Tuple[str, str, str]] = {}


def _integrate_opsin_carbohydrates():
    """Integrate OPSIN carbohydrate entries into the sugar lookup.

    Adds simpleGroup entries (complete molecules like meglumine, sorbitol)
    and ring entries (cyclic sugars like ascorbic acid, garosamine) from the
    OPSIN carbohydrate XML data. Hand-curated entries always win on conflict.

    Excludes disaccharides (2+ rings) to prevent decomposition interference.
    """
    try:
        from .opsin_imports.carbohydrates_opsin import OPSIN_CARBOHYDRATES
    except ImportError:
        logger.debug("OPSIN carbohydrates import not available")
        return

    for key, entry in OPSIN_CARBOHYDRATES.items():
        sub_type = entry.get('subType', '')
        if sub_type not in ('simpleGroup', 'ring'):
            continue

        smiles = entry.get('smiles', '')
        if not smiles or smiles == '*' or '*' in smiles:
            continue

        names = entry.get('names', [])
        if not names:
            continue

        # Canonicalize the SMILES
        try:
            mol = Chem.MolFromSmiles(smiles)
            if mol is None:
                continue
            can_smiles = Chem.MolToSmiles(mol, canonical=True)
        except Exception:
            continue

        # Exclude disaccharides and larger oligosaccharides (2+ rings).
        # These interfere with the decomposition engine's fragment naming
        # when complex glycosides are cleaved at glycosidic bonds.
        ri = mol.GetRingInfo()
        if ri.NumRings() >= 2:
            continue

        # Hand-curated entries always win on conflict
        if can_smiles in ALL_SUGAR_NAMES:
            continue

        # Use the first name as the base name
        base_name = names[0]

        # Store as (anomer="", config="", base_name) since OPSIN entries
        # don't distinguish anomer/config at this level
        OPSIN_SUGAR_NAMES[can_smiles] = ("", "", base_name)

    # Merge OPSIN entries into ALL_SUGAR_NAMES
    ALL_SUGAR_NAMES.update(OPSIN_SUGAR_NAMES)


_integrate_opsin_carbohydrates()


