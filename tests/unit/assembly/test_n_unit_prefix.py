"""PS lane 2: the prefix of a hydrazinyl unit and of an imine joined through nitrogen.

A fragment rooted at such a nitrogen was named as a free molecule ('methylhydrazine',
'methanimine') and a prefix cut from that name by the ring rule of ('-ine' to '-inyl'),
which gave '4-(methylhydrazinyl)benzoic acid' and '2-methaniminylbenzoic acid' at pin_verified.
Both words are wrong, and the round trip cannot see it (OPSIN 2.9.0 reads each back to the right
structure, as it does '4-(2-methylhydrazin-1-yl)benzoic acid'):

* Hydrazinyl. "Citation of locants" (the Blue Book): "if any locants are essential
  for defining the structure of the parent structure or of a unit of structure as defined by its
  appropriate enclosing marks, then all locants must be cited". "Omission of locants"
  (:2953): "Locants are omitted when no isomer can be generated by moving suffixes and/or
  prefixes (if any) from their position to another or by interchanging them between two
  different positions". A methyl on the unit can be on either nitrogen, so '2-methylhydrazin-1-yl';
  an ylidene can be on the far nitrogen only, 'ethylidenehydrazinyl (preferred prefix) (not
  2-ethylidenehydrazin-1-yl)' (:2959). PINs: '4-(1-acetyl-2-ethylhydrazin-1-yl)benzoic acid (PIN)'
   "Substituent groups derived from hydrazides",:34042), '3-(2-carbamoylhydrazin-1-yl)
  propanoic acid (PIN)' "Semicarbazides",:38644), '2-nitrohydrazin-1-yl
  (preselected prefix)',:36437).
* Imine. '-iminyl' is the suffix of the radical =N•,:40620; Table 7.2 "Suffixes for
  Radicals of Amines, Imines and Amides",:40622). R-CH=N- joined through nitrogen is the amino
  prefix with its ylidene: '4-{[(4-chlorophenyl)methylidene]amino}aniline (PIN)'
  "Substitutive names for imines",:26529), '4-[(diaminomethylidene)amino]butanoic acid (PIN)'
  ,:34282). R-C(=NH)- joined through carbon is an acyl group, 'methanimidoyl
  (preferred prefix)',:26540,:30468).

The hydrazide group R-CO-NH-NH- has the PIN prefix 'acetohydrazido'; its acylhydrazinyl form is
the book's second method,:34020) and is not shipped as a PIN.

Producer: ``assembly/n_unit_prefix.py`` (the structure), ``hetero_group_prefixes._hydrazinyl``
(the locants), ``capped_name.acyclic_n_parent`` (the ring rule no longer applies)."""
