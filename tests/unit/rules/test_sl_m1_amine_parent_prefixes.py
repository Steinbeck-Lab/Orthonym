"""SL lane M, item M1: the parent of a secondary or tertiary amine whose nitrogen is bonded to
several carbons, and the ring bonded to the nitrogen.

``CN(C)Cc1ccccc1`` declined at the default tier, ``C[N+](C)(C)Cc1ccccc1`` was named
'N-benzyl-N,N-dimethylmethanaminium' and shipped as the PIN, and the name of ``CNCc1ccccc1`` and of
``CCN(C)Cc1ccccc1`` depended on how the SMILES was written. One cause:

* "SENIORITY OF ANY PARENT STRUCTURE" (the Blue Book): "The senior parent structure has
  the maximum number of substituents corresponding to the principal characteristic group (suffix)". The
  amine nitrogen is the suffix of every chain and ring it is bonded to. The perceived match keeps ONE
  carbon of the nitrogen (the one with most heavy neighbours, then the lowest index), and the count of
  the groups a candidate holds read only that carbon: for ``CN(C)Cc1ccccc1`` the methyl chain and the
  ring both read 0, the ring won the tie, and the amine had no parent; for ``CC(C)(C)Nc1ccccc1`` the
  tert-butyl carbon was kept, the chain read 1 and the ring 0, against "Selection of the
  principal chain or senior ring system in secondary and tertiary amines" (:26247): "When a choice for
  parent hydride is possible between a ring and a chain, the ring is preferred." (:26249;
  '(PIN) N-cyclohexylaniline', 'N-butylcyclopropanamine (not N-cyclopropylbutan-1-amine)').
* "CRITERIA RELATED TO NUMBER AND LOCATION OF SUBSTITUENT GROUPS" (:21596,:21604): "The
  preferred IUPAC name is based on the senior parent structure that has the maximum number of
  substituents cited as prefixes". Among the one-carbon chains of ``CN(C)Cc1ccccc1`` (two methyls and the
  benzylic carbon) the benzylic carbon cites three prefixes (phenyl and two methyls on N), a methyl two
  (benzyl and a methyl on N). The chain selector did not count a ring bonded to the chain, and a chain of
  one carbon was never compared with its peers: the choice was the order of the atoms of the SMILES.
  A longer chain wins before is reached, "SENIORITY OF ACYCLIC CHAINS (THE PRINCIPAL
  CHAIN)" (:20916) "(b) has the greater number of skeletal atoms": ``CCN(C)Cc1ccccc1`` keeps the ethane
  parent, 'N-benzyl-N-methylethan-1-amine'.

The locant '1' of the phenyl on the one-carbon parent is decided by (:2953), not by this
lane: "Locants are omitted when no isomer can be generated by moving suffixes and/or prefixes (if any)
from their position to another" -- the rule the SF lane A item 6 test pins
(``test_sf_a6_one_carbon_amine_locant.py``; '1-hydrazinylmethanamine (PIN)':38535 where the nitrogen holds
a hydrogen, 'cyano-N,N-dimethylmethanamine N-oxide (PIN)':36580 where it holds none). So the secondary
amine and the protonated tertiary amine cite it and the neutral and quaternary tertiary amine omit it.
The brief of this lane wrote '1-phenyl' for those two as well; the book's example:36580 and the
engine's licence (``locant_omission.mononuclear_parent_locant_required``) decide otherwise.

Changed asserted values, none: every row below is new. Every name is read back by OPSIN 2.9.0 to the
full InChIKey of its structure (the ``opsin_gate`` marker puts the engine's own gate on).
"""
import random

import pytest
from rdkit import Chem

from orthonym import Orthonym
from orthonym.perception.chains import p45_pending
from orthonym.rules.parent_selection import (
    BRIDGING_HETEROATOM_PGS,
    _count_pg_on_chain,
    _count_pg_on_ring,
    bridging_group_reaches,
)

pytestmark = [pytest.mark.unit, pytest.mark.opsin_gate]


def _tiered(smiles: str):
    row = Orthonym().name_tiered(smiles)
    return row["name"], row["tier"]


def _spellings(smiles: str, n: int = 8, seed: int = 11):
    """``smiles`` and ``n`` more spellings of its molecule (atom order permuted, not canonical)."""
    mol = Chem.MolFromSmiles(smiles)
    rng = random.Random(seed)
    out = [smiles, Chem.MolToSmiles(mol)]
    for _ in range(n):
        order = list(range(mol.GetNumAtoms()))
        rng.shuffle(order)
        out.append(Chem.MolToSmiles(Chem.RenumberAtoms(mol, order), canonical=False))
    return list(dict.fromkeys(out))


# ---- the rows of the lane: among the one-carbon chains --------------------------------

@pytest.mark.parametrize("smiles, expected", [
    # neutral tertiary amine: no hydrogen on N, nothing could move to it: the locant is omitted
    ("CN(C)Cc1ccccc1", "N,N-dimethyl(phenyl)methanamine"),
    # quaternary: the same position structure
    ("C[N+](C)(C)Cc1ccccc1", "N,N,N-trimethyl(phenyl)methanaminium"),
    # the hydron of the protonated tertiary amine can take the phenyl: the locant is cited (SF-A item 6)
    ("C[NH+](C)Cc1ccccc1", "N,N-dimethyl-1-phenylmethanaminium"),
    # secondary amine: N-H, cited
    ("CNCc1ccccc1", "N-methyl-1-phenylmethanamine"),
    # a ring on the carbon that is not benzene
    ("CN(C)Cc1ccccn1", "N,N-dimethyl(pyridin-2-yl)methanamine"),
    ("CN(C)Cc1ccccc1Cl", "(2-chlorophenyl)-N,N-dimethylmethanamine"),
])
def test_the_one_carbon_parent_is_the_carbon_with_most_prefixes(smiles, expected):
    name, tier = _tiered(smiles)
    assert (name, tier) == (expected, "pin_verified")


@pytest.mark.parametrize("smiles", [
    "CN(C)Cc1ccccc1", "C[N+](C)(C)Cc1ccccc1", "C[NH+](C)Cc1ccccc1", "CNCc1ccccc1",
])
def test_the_name_does_not_depend_on_how_the_smiles_is_written(smiles):
    """The parent was chosen by the order of the atoms: 'CN(C)Cc1ccccc1' declined, 'CN(C)C'
    was named; 'CNCc1ccccc1' declined, 'C(NC)c1ccccc1' was named."""
    names = {_tiered(s) for s in _spellings(smiles)}
    assert len(names) == 1, names


# ---- the controls: a longer chain, or a ring, is senior before -----------------------

@pytest.mark.parametrize("smiles, expected", [
    # (b): the ethane chain has the greater number of skeletal atoms than the benzylic carbon
    ("CCN(C)Cc1ccccc1", "N-benzyl-N-methylethan-1-amine"),
    ("CCNCc1ccccc1", "N-benzylethan-1-amine"),
    ("CC(C)N(C)Cc1ccccc1", "N-benzyl-N-methylpropan-2-amine"),
    ("CCCN(CC)Cc1ccccc1", "N-benzyl-N-ethylpropan-1-amine"),
    # no ring: untouched ('N,N,N-trimethylmethanaminium (PIN)' the Blue Book)
    ("C[N+](C)(C)C", "N,N,N-trimethylmethanaminium"),
    ("CC[NH2+]C", "N-methylethanaminium"),
    ("CC[NH+](C)C", "N,N-dimethylethanaminium"),
    ("CN(C)C", "N,N-dimethylmethanamine"),
])
def test_a_longer_chain_or_no_ring_keeps_its_name(smiles, expected):
    assert _tiered(smiles) == (expected, "pin_verified")


@pytest.mark.parametrize("smiles", ["CCN(C)Cc1ccccc1", "CCNCc1ccccc1", "CCCN(CC)Cc1ccccc1"])
def test_the_longer_chain_is_the_parent_in_every_spelling(smiles):
    """The ethane chain lost to the ring in a tie when the benzylic carbon had the lower index:
    'C(N(CC)C)c1ccccc1' and 'C(NCC)c1ccccc1' declined."""
    assert len({_tiered(s) for s in _spellings(smiles)}) == 1


# ----: the ring bonded to the nitrogen is the parent ----------------------------------

@pytest.mark.parametrize("smiles, expected", [
    ("CC(C)(C)Nc1ccccc1", "N-tert-butylaniline"),
    ("CC(C)Nc1ccccc1", "N-(propan-2-yl)aniline"),
    ("CCC(C)Nc1ccccc1", "N-(butan-2-yl)aniline"),
    ("CC(c1ccccc1)Nc1ccccc1", "N-(1-phenylethyl)aniline"),
    ("CC(c1cccs1)Nc1cccnc1", "N-[1-(thiophen-2-yl)ethyl]pyridin-3-amine"),
    ("CC(C1=CC=CS1)NC2=NN(C=C2)C", "1-methyl-N-[1-(thiophen-2-yl)ethyl]-1H-pyrazol-3-amine"),
    ("CCCCNC1CC1", "N-butylcyclopropanamine"),
])
def test_the_ring_on_the_nitrogen_is_the_parent(smiles, expected):
    """ (:26249): the ring is preferred; the carbon of the chain that the match kept
    (tert-butyl, isopropyl, the CH of a 1-phenylethyl) decided it before, by its index."""
    assert _tiered(smiles) == (expected, "pin_verified")


@pytest.mark.parametrize("smiles", ["CC(C)(C)Nc1ccccc1", "CC(C)Nc1ccccc1", "CC(c1ccccc1)Nc1ccccc1"])
def test_the_ring_is_the_parent_in_every_spelling(smiles):
    assert len({_tiered(s) for s in _spellings(smiles)}) == 1


@pytest.mark.parametrize("smiles, chain_parent_name", [
    ("CC(c1ccncc1)Nc1ccccc1", "N-phenyl-1-(pyridin-4-yl)ethan-1-amine"),
    ("CC(C1=CC=CS1)NC2CCC3=CC=CC=C3C2", "N-(1,2,3,4-tetrahydronaphthalen-2-yl)-1-(thiophen-2-yl)ethan-1-amine"),
])
def test_a_chain_parent_name_over_a_ring_is_never_shipped_as_the_pin(smiles, chain_parent_name):
    """Where no producer builds the ring-parent name, the chain-parent name is no PIN,
    :26249) and the default tier declines it: main shipped these as pin_verified. The best-effort
    tier keeps a name that reads back, labelled below the PIN."""
    name, tier = _tiered(smiles)
    assert not (name == chain_parent_name and tier == "pin_verified")
    best_effort = Orthonym(general_fallback=True, general_fallback_unverified=True,
                           allow_aromatic_general=True).name_tiered(smiles)
    assert best_effort["tier"] != "abstain"
    assert not (best_effort["name"] == chain_parent_name and best_effort["tier"] == "pin_verified")


# ---- the sites -----------------------------------------------------------------------------------

def _features(smiles):
    namer = Orthonym(_disable_opsin_validity_gate=True)
    mol = Chem.MolFromSmiles(smiles)
    canonical = Chem.MolToSmiles(mol)
    features = namer._perceive(mol, canonical, canonical)
    namer._classify(features)
    return mol, features


def test_the_bridging_groups_are_the_secondary_and_tertiary_amines():
    assert BRIDGING_HETEROATOM_PGS == {"secondary_amine", "tertiary_amine"}


@pytest.mark.parametrize("smiles, chain, ring", [
    # N is bonded to the methyl chain, to the benzylic carbon and to a methyl: the count asks N
    ("CN(C)Cc1ccccc1", [0], [4, 5, 6, 7, 8, 9]),
    ("C(N(CC)C)c1ccccc1", [2, 3], [5, 6, 7, 8, 9, 10]),
])
def test_the_count_of_a_group_is_per_nitrogen_not_per_kept_carbon(smiles, chain, ring):
    mol, features = _features(smiles)
    groups = features.principal_group_atoms
    assert features.principal_group in BRIDGING_HETEROATOM_PGS
    assert _count_pg_on_chain(mol, chain, groups, features.principal_group) == 1
    assert _count_pg_on_ring(mol, set(ring), groups, features.principal_group) == 0
    assert bridging_group_reaches(mol, features.principal_group, groups[0], set(chain))
    assert not bridging_group_reaches(mol, features.principal_group, groups[0], set(ring))


def test_the_ring_on_the_nitrogen_counts_one_as_the_chain_does():
    mol, features = _features("CC(C)(C)Nc1ccccc1")
    group = features.principal_group_atoms[0]
    ring = {a.GetIdx() for a in mol.GetAtoms() if a.GetIsAromatic()}
    chain = [0, 1, 2]                         # the tert-butyl chain: N is bonded to the middle carbon
    assert _count_pg_on_ring(mol, ring, features.principal_group_atoms, features.principal_group) == 1
    assert _count_pg_on_chain(mol, chain, features.principal_group_atoms, features.principal_group) == 1
    assert bridging_group_reaches(mol, features.principal_group, group, ring)


def test_a_group_that_is_not_a_bridging_amine_is_not_asked_of_the_nitrogen():
    mol = Chem.MolFromSmiles("CC(=O)Nc1ccccc1")
    assert not bridging_group_reaches(mol, "secondary_amide", (2, 1), {0, 1})
    assert not bridging_group_reaches(mol, "primary_amine", (0, 1), {1})
    assert not bridging_group_reaches(mol, "secondary_amine", (), {1})


@pytest.mark.parametrize("smiles, pending", [
    # an amine on a one-carbon chain whose nitrogen has other carbons: compared
    ("CN(C)Cc1ccccc1", True),
    ("CNCc1ccccc1", True),
    # a chain of two carbons or more: compared as before
    ("CCN(C)Cc1ccccc1", True),
    ("CC(C)(C)Nc1ccccc1", True),
    # a group whose producer does not build on the given chain, or a chain of one carbon of a
    # group whose nitrogen cannot bridge: never
    ("OCc1ccccc1", False),
    ("NCc1ccccc1", False),
])
def test_p45_pending_compares_one_carbon_chains_of_an_amine(smiles, pending):
    mol, features = _features(smiles)
    chain = features.principal_chain or [next(a.GetIdx() for a in mol.GetAtoms() if a.GetSymbol() == "C"
                                              and not a.GetIsAromatic())]
    assert p45_pending(features, chain) is pending


def test_p45_pending_is_false_without_a_chain():
    _mol, features = _features("CN(C)Cc1ccccc1")
    assert p45_pending(features, []) is False
    assert p45_pending(features, None) is False
