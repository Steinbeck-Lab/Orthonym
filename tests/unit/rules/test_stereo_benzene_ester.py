"""Tests for stereodescriptor integration in benzene, ester, lactone, lactam paths.

Phase 63, Plan 02: Verifies that stereo descriptors are correctly included
in names generated by these four naming paths. Each test validates against
RDKit's rdCIPLabeler output rather than hardcoded R/S values.

Markers: @pytest.mark.unit
"""

import pytest
from rdkit import Chem
from rdkit.Chem import rdCIPLabeler

from orthonym import name_compound


def _has_stereo_in_name(name: str) -> bool:
    """Check if a name contains any stereodescriptor prefix like (2R)- or (4E)-."""
    import re
    # Match patterns like (2R), (3S), (4E), (5Z) etc. in the name
    return bool(re.search(r'\(\d+[RSEZ]', name))


def _get_cip_labels(smiles: str) -> dict:
    """Get CIP labels from a SMILES string.

    Returns dict with:
        atoms: list of (atom_idx, cip_code) for stereocenters
        bonds: list of (begin_idx, end_idx, cip_code) for stereo bonds
    """
    mol = Chem.MolFromSmiles(smiles)
    assert mol is not None, f"Invalid SMILES: {smiles}"
    rdCIPLabeler.AssignCIPLabels(mol)

    atoms = []
    for atom in mol.GetAtoms():
        if atom.HasProp('_CIPCode'):
            atoms.append((atom.GetIdx(), atom.GetProp('_CIPCode')))

    bonds = []
    for bond in mol.GetBonds():
        if bond.HasProp('_CIPCode'):
            bonds.append((bond.GetBeginAtomIdx(), bond.GetEndAtomIdx(),
                          bond.GetProp('_CIPCode')))

    return {'atoms': atoms, 'bonds': bonds}


# =========================================================================
# Benzene stereo tests
# =========================================================================

class TestBenzeneStereo:
    """Test stereodescriptor inclusion in benzene naming paths."""

    @pytest.mark.unit
    def test_benzene_chiral_substituent_includes_stereo(self):
        """Benzene with chiral substituent should include stereo in name.

        1-phenylethan-1-ol has a stereocenter on the alpha carbon.
        The name should include (1R)- or (1S)- prefix.
        """
        smiles = 'O[C@@H](C)c1ccccc1'
        cip = _get_cip_labels(smiles)
        assert len(cip['atoms']) > 0, "SMILES should have stereocenters"

        name = name_compound(smiles)
        assert _has_stereo_in_name(name), (
            f"Expected stereo prefix in name for chiral benzene derivative, "
            f"got: {name}"
        )

    @pytest.mark.unit
    def test_plain_benzene_no_stereo_regression(self):
        """Plain substituted benzene without stereo should not get stereo prefix."""
        smiles = 'Cc1ccc(C)cc1'
        name = name_compound(smiles)
        assert name == '1,4-dimethylbenzene', f"Expected '1,4-dimethylbenzene', got: {name}"
        assert not _has_stereo_in_name(name), (
            f"Plain benzene should not have stereo prefix, got: {name}"
        )

    @pytest.mark.unit
    def test_monosubstituted_benzene_no_stereo(self):
        """Monosubstituted benzene without stereo should not get stereo prefix."""
        smiles = 'Clc1ccccc1'
        name = name_compound(smiles)
        assert name == 'chlorobenzene', f"Expected 'chlorobenzene', got: {name}"
        assert not _has_stereo_in_name(name)


