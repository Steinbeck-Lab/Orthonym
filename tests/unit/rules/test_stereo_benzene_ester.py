    @pytest.mark.unit
    def test_lactam_stereo_locant_matches_cip(self):
        """Verify the stereo locant in lactam name matches CIP assignment."""
        smiles = 'O=C1N[C@@H](C)CC1'
        mol = Chem.MolFromSmiles(smiles)
        rdCIPLabeler.AssignCIPLabels(mol)

        # Get the CIP code
