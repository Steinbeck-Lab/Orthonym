class TestEsterStereo:
    """Test stereodescriptor inclusion in ester naming path."""

    @pytest.mark.unit
    def test_ester_ez_acid_chain(self):
        """Ester with E/Z on acid chain should include E/Z in name.

        methyl (4E)-octa-4,7-dienoate has E geometry at C4=C5.
        """
        smiles = 'C=CC/C=C/CCC(=O)OC'
        cip = _get_cip_labels(smiles)
        assert len(cip['bonds']) > 0, "SMILES should have E/Z bonds"

        name = name_compound(smiles)
        assert '(4E)' in name, (
            f"Expected (4E) in ester name for E-configured acid chain, "
            f"got: {name}"
        )

    @pytest.mark.unit
    def test_ester_z_alkyl_chain(self):
        """Ester with Z on alkyl chain should include Z in name.

        pentadec-10-en-1-yl acetate has Z geometry.
        """
        smiles = r'CCCC/C=C\CCCCCCCCCOC(C)=O'
        cip = _get_cip_labels(smiles)
        assert len(cip['bonds']) > 0, "SMILES should have E/Z bonds"

        name = name_compound(smiles)
        assert 'Z' in name, (
            f"Expected Z descriptor in ester name for Z-configured alkyl chain, "
            f"got: {name}"
        )

    @pytest.mark.unit
    def test_ester_no_stereo_baseline(self):
        """Plain ester without stereo should not get stereo prefix."""
        smiles = 'COC(=O)CCC'
        name = name_compound(smiles)
        assert name == 'methyl butanoate', f"Expected 'methyl butanoate', got: {name}"
        assert not _has_stereo_in_name(name)

    @pytest.mark.unit
    def test_ester_ez_not_duplicated(self):
        """E/Z descriptor should appear exactly once, not duplicated."""
        smiles = 'C=CC/C=C/CCC(=O)OC'
        name = name_compound(smiles)
        # Count occurrences of (4E)
        count = name.count('(4E)')
        assert count == 1, (
            f"Expected exactly one (4E) in name, found {count}: {name}"
        )


