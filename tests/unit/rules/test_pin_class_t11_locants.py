"""PIN class program, Task 11: locants (LOCANT_OMIT, LOCANT_REQUIRED, LOCANT_SPURIOUS,
CUMULENE_LOCANTS).

 "Citation of locants" (the Blue Book,:2869) is the default: "if any locants
are essential... then all locants must be cited"; "Omission of locants" (:2871)
grants the licences.

(A) A chain parent compound whose substitutable hydrogens all sit on one atom.
     (:3031): "All locants are omitted for parent compounds when all
    substitutable hydrogen atoms have the same locant" ('difluoroacetic acid (PIN) (not
    2,2-difluoroacetic acid)'); (:3007): hydrogens on chalcogens and on a
    formyl carbon are not substitutable. (:7304): "Simple substituents of a
    parent where only one possible position can be substituted do not require locants.
    Enclosing marks are used with second and subsequent simple substituents... Locants
    are required for related compounds where additional substitutable positions are
    available, for example acetamide" ('bromo(chloro)acetic acid (PIN)',:7312).
    Rows: 'cyanoacetyl chloride (PIN)' (:5112), 'amino(oxo)ethaneperoxoic acid (PIN)'
    (:30182), '*S*-methyl (ethylsulfanyl)(sulfanylidene)ethanethioate (PIN)' (:32019),
    'chloroacetic chloroethanethioic anhydride'. The licence is
    ``assembly.locant_omission.l6_chain_parent_one_substitutable_atom``, applied where
    the producers write their prefix locants (``composer._integrate_universal_prefixes``,
    ``polyfunctional`` and ``general_acyclic`` assembly, the thioacid component of an
    anhydride).

(B) A ring parent whose substitutable hydrogens all sit on one ring atom.:
    'chlorotrioxetane (PIN) (not 4-chloro-1,2,3-trioxetane)' (:3187), 'dichlorotrioxetane
    (PIN)' (:3029): the parent's heteroatom locants go too. Built in
    ``rules/heterocycles.py:name_substituted_heterocycle`` with the Hantzsch-Widman parent
    rebuilt without its locant set (``build_hw_name(cite_locants=False)``) only when the
    same builder reproduces the cited parent name.
(C) Formamide completely N-substituted in the same way. (:32774)
    'dimethylformamide (PIN)' (:32782); (:3007); formamide's substitutable
    hydrogens are the two N-H ('carbonochloridic amide (PIN) (not 1-chloroformamide)',
    :32707); one N-substituent keeps its locant ('N-phenylformamide (PIN)',:32855).
(D) A homogeneous Se/Te chain substituent. ("Compounds with three or more
    contiguous identical chalcogen atoms are treated as parent hydrides") and
    (:39383): '1-(methyltriselanyl)propan-1-one (PIN; a pseudoketone)' (:39397) -- the
    chain is named on its own stem with the free valence at locant 1, as the sulfur
    chain already was ('methyltrisulfanyl'); the Se/Te chain used to go through the
    radical route, which kept the parent hydride's numbering ('1-methyltriselanyl').
(E) A diazene whose nitrogen carries a positional isotope label. (:44180):
    "if isotopic modification requires a locant to specify its position, then all
    locants must be specified and none are omitted"; (:44261)
    '1-(naphthalen-2-yl)-2-phenyl(1-15N)diazene (PIN)' (:44267) and
    '1-(naphthalen-2-yl)-2-phenyl[2-15N]diazene (PIN)' (:44381): the substituent cited
    first in alphanumerical order keeps locant 1 whichever nitrogen is labelled. The
    unlabelled parent is '(naphthalen-2-yl)(phenyl)diazene (PIN)' (:38789). A label on
    a substituent ring, or on both nitrogens, needs no parent locant and is unchanged.
(F) A labelled one-carbon substituent backbone. (:44180): "locants are
    omitted if no locants are necessary in unmodified names"; on 'methyl' every
    position is locant 1, so no label there needs a locant:
    '{[(2H1)methoxy(2H2)methyl]sulfanyl}methaneperoxol (PIN)' (:44188).
(G) Cyclic cumulenes. (:16586): "Cyclic cumulenes are composed entirely of
    atoms, identical or different, linked by double bonds. For homocyclic cumulenes
    omission of all locants is recommended for preferred IUPAC names (see ":
    'cycloundecaundecaene (PIN)' (:16592), '1λ4,2λ4-dithiacycloundecaundecaene (PIN)'
    (:16596) -- the ene locants go, the heteroatom locants stay. The dithia ring needs the
    λ form in the cyclic 'a' builder,:9158), which now names the λ rings it
    used to decline ('1-oxa-4λ4-thiacyclotetradecane (PIN)',:9486).
(H) A one-atom chain parent whose suffix nitrogen holds a hydrogen or carries a prefix
    that could stand on the carbon. The deciding rule is (:2957) "Locants are
    omitted when no isomer can be generated by moving suffixes and/or prefixes (if any)
    from their position to another or by interchanging them between two different
    positions"; (a) (:2891) speaks of parent hydrides only. A substituent
    attached through an acyclic carbon cannot move to C1 without changing the parent
    ('cyano-N,N-dimethylmethanamine N-oxide (PIN)',:36580); a ring or a heteroatom can
    ('N,1-bis(4-chlorophenyl)methanimine (PIN)',:26524; '(1E)-1-[...]-N-[...]methanimine
    (PIN)',:50452). All prefixes are cited in order; unlocanted second prefixes
    on the one-atom parent are enclosed:7272,:47666). Also:
     (a) (:2891) omits '1' "in substituted mononuclear parent hydrides", but
     (:7304): "Locants are required for related compounds where additional
    substitutable positions are available, for example acetamide" --
    '1-hydrazinylmethanamine (PIN)' (:38535). The -OH of methanol is not substitutable
    ,:3007), so 'chloromethanol' keeps its omission; a fully substituted
    nitrogen is left as it is ('cyano-N,N-dimethylmethanamine N-oxide (PIN)',:36580).
"""
