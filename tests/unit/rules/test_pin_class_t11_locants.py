@pytest.mark.parametrize("labelled,atoms,expected", [
    ("c1ccc(N=[15N]c2ccc3ccccc3c2)cc1", "NN", True),
    ("c1ccc(N=Nc2ccc3ccccc3c2)c([2H])c1", "NN", False),   # the label is on the ring
    ("c1ccc(N=Nc2ccc3ccccc3c2)c([2H])c1", "ring", True),
])
def test_isotope_label_on_atoms(labelled, atoms, expected):
    from orthonym.assembly.locant_omission import (
        isotope_label_on_atoms, isotope_labelled_original_scope)
    mol = Chem.MolFromSmiles("c1ccc(N=Nc2ccc3ccccc3c2)cc1")
    if atoms == "NN":
        idx = [a.GetIdx() for a in mol.GetAtoms() if a.GetSymbol() == "N"]
    else:
        idx = [0, 1, 2, 3, 16, 17]          # the phenyl ring
    assert isotope_label_on_atoms(mol, idx) is False      # nothing declared
    with isotope_labelled_original_scope(Chem.MolFromSmiles(labelled)):
        assert isotope_label_on_atoms(mol, idx) is expected


