def test_derived_uncertified_record_follows_its_skeleton():
    """``record_derived_uncertified_pin_name``: the decorated name inherits the record only
    from a skeleton that carries one,:44180)."""
    import contextvars

    from orthonym.metrics import provenance as pv

    def run():
        pv.clear_provenance()
        pv.record_uncertified_pin_name("1,2-dimethyl-1λ6,2λ4-disulfane-1,1,2-trione")
        pv.record_derived_uncertified_pin_name(
            "1,2-dimethyl-1λ6,2λ4-disulfane-1,1,2-trione",
            "1,2-di[(13C)methyl]-1λ6,2λ4-disulfane-1,1,2-trione")
        pv.record_derived_uncertified_pin_name(
            "1,2-dimethylbenzene", "1,2-di[(13C)methyl]benzene")
        return pv.get_provenance()["uncertified_pin_names"]

    names = contextvars.copy_context().run(run)
    assert "1,2-di[(13C)methyl]-1λ6,2λ4-disulfane-1,1,2-trione" in names
    assert "1,2-di[(13C)methyl]benzene" not in names


