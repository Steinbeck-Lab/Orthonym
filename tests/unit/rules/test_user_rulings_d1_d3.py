"""User rulings D1 and D3 (2026-10-02): where the Blue Book prints a different PIN for the
same structure, the engine follows the printed PIN.

(D1a) A prefix on a mancude heteromonocycle with one kind of substitutable hydrogen cites its
    locant. (the Blue Book) "Method (1), (3), or (5) leads to preferred
    IUPAC names": '(1) 2-[(pyridin-3-yl)oxy]pyrazine (PIN)' (:27772). The
    licence (:2939) "The locant is omitted in monosubstituted symmetrical parent hydrides
    or parent compounds where there is only one kind of substitutable hydrogen" keeps the
    rows it prints: a suffix, 'pyrazinecarboxylic acid (PIN)' (:2949), and a prefix on a
    carbocycle, 'chlorocoronene (PIN)' (:2947). A saturated ring is not mancude:
    'phenyloxirane (PIN)' (:2035).
(D1b) Identical substituents on the two chalcogen atoms of a λ dichalcogane with unequal
    bonding numbers cite no locants. (:39545) "Method (1) generates preferred
    IUPAC names" (:39552): 'diethyl-1λ6,2λ4-diselane-1,1,2-trione (PIN)' (:39562); equal
    bonding numbers cite them, '1,2-dimethyl-1λ4,2λ4-disulfane-1,2-dione (PIN)' (:39554),
    and so do different substituents, '1-ethyl-2-methyl-1λ6,2λ6-disulfane-1,1,2,2-tetrone
    (PIN)' (:39556).
(D1c) H2N-CO-X (X a halogen) is an amide of a carbonic acid. (:32699):
    "Substitution of the aldehydic hydrogen is subject to limitations (see " --
    'Cl-CO-NH2 carbonochloridic amide (PIN) (not 1-chloroformamide)' (:32705-:32707);
     (:30672) lists -F, -Cl, -Br, -I among the substituents of formic acid whose
    names "are derived from carbonic acid by functional replacement nomenclature"
    (:30674). The N-substituted carbamoyl halides and the carbamoyl pseudohalides keep their
    names ('carbamoyl isocyanate (PIN)',:31488; 'carbamoyl cyanide (PIN)',:34858).
(D3) A C-substituent of a one-carbon sulfonamide cites '1-'. (:2953): "Locants
    are omitted when no isomer can be generated by moving suffixes and/or prefixes (if any)
    from their position to another or by interchanging them between two different
    positions" -- the chloro could stand on the sulfonamide nitrogen
    ('N-chloromethanesulfonamide'); (:32991, "Method (1) generates preferred
    IUPAC names":32998) prints '(1) (1-cyclohexylmethanesulfonamido)acetic acid' (:33024).
    The licence is the one of the one-carbon amines ('1-hydrazinylmethanamine (PIN)',
    :38535): ``assembly.locant_omission.mononuclear_parent_locant_required``, which now
    counts the nitrogen atoms of the principal group joined to the carbon through the
    group (the sulfonamide nitrogen sits on the sulfur).
"""
