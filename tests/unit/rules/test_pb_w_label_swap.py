# ------------------------------------------------------------ the two helpers (no OPSIN)
def _branch(mol, n_idx, start):
    """The atoms reached from ``start`` without passing through ``n_idx``."""
    seen, stack = set(), [start]
    while stack:
        a = stack.pop()
        if a in seen:
            continue
        seen.add(a)
        stack.extend(x.GetIdx() for x in mol.GetAtomWithIdx(a).GetNeighbors() if x.GetIdx() != n_idx)
    return sorted(seen)


def _ring_and_other(smiles):
    """(mol, N, the ring branch's atoms, the branch of the other carbon neighbour) of the
    first nitrogen."""
    mol = Chem.MolFromSmiles(smiles)
    n = next(a.GetIdx() for a in mol.GetAtoms() if a.GetSymbol() == "N")
    nbrs = [x.GetIdx() for x in mol.GetAtomWithIdx(n).GetNeighbors()]
    ring = next(i for i in nbrs if mol.GetAtomWithIdx(i).GetIsAromatic())
    other = next(i for i in nbrs if i != ring)
    return mol, n, _branch(mol, n, ring), _branch(mol, n, other)


