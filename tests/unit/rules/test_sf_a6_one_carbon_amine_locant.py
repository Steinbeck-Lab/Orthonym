"""SF lane A item 6: the locant '1' of a group on the carbon of 'methanamine' / 'methanaminium'.

 "Omission of locants", (the Blue Book): "Locants are omitted when no isomer can
be generated by moving suffixes and/or prefixes (if any) from their position to another or by
interchanging them between two different positions." The parent has two positions, the carbon and the
nitrogen of the suffix, so the locant '1' of a group on the carbon is cited exactly when a group can
move between them:

* the nitrogen holds a hydrogen: '1-hydrazinylmethanamine (PIN)' (:38535);
* the carbon holds a hydrogen and a group of the nitrogen that keeps the parent (a ring atom or a
  heteroatom) could stand on it: 'N,1-bis(4-chlorophenyl)methanimine (PIN)' (:26524);
* otherwise no isomer exists: 'cyano-N,N-dimethylmethanamine N-oxide (PIN)' (:36580,
  "aci-Nitro compounds"; the Blue Book edition on the IUPAC site prints it without a '1-' too) and
  '(Z)-N-hydroxy(4-chlorophenyl)(phenyl)methanimine (PIN)' (:47666).

So the neutral 'methoxy-N,N-dimethylmethanamine' and the quaternary 'methoxy-N,N,N-trimethyl-
methanaminium' (no hydrogen on the nitrogen) are right as they stand, and the protonated tertiary amine,
whose nitrogen holds the hydron, cites the locant: '1-methoxy-N,N-dimethylmethanaminium'. The cation was
named by re-entering the neutral amine, whose licence read the nitrogen without the hydron
(rules.charged_router._reenter, locant_omission.suffix_nitrogen_gains_hydron).

Changed asserted values, none: the new rows are new. Machine-confirmed: OPSIN 2.9.0 reads every name
below back to the full InChIKey of its structure; the tests fail on the tree before the change
(an A/B check). Unverified by the book: no example prints a protonated tertiary amine with a group on the
carbon; the rule is the one the Blue Book's own examples fix for the neutral amines.
"""
import pytest
from rdkit import Chem

from orthonym.namer import Orthonym
from orthonym.validation.pin_spelling import check_pin_spelling

pytestmark = pytest.mark.unit


def _name(smiles: str) -> str:
    return Orthonym().name(smiles)


@pytest.mark.parametrize("smiles, expected", [
    # the protonated tertiary amine holds a hydrogen: the group on the carbon could move to it
    ("COC[NH+](C)C", "1-methoxy-N,N-dimethylmethanaminium"),
    ("ClC[NH+](C)C", "1-chloro-N,N-dimethylmethanaminium"),
    ("CC1=CC=C(C=C1)CN2C=CC=C2C[NH+](CC3=CC=CC=C3)CC4=CC=CC=C4",
     "N,N-dibenzyl-1-{1-[(4-methylphenyl)methyl]-1H-pyrrol-2-yl}methanaminium"),
    # the same shape reached through the ester parent of the neutral amine (single-substitutable-atom licence)
    ("CC(=O)OC[NH+](C)C", "1-(acetyloxy)-N,N-dimethylmethanaminium"),
    ("CSC[NH+](C)Cc1ccccc1", "N-benzyl-N-methyl-1-(methylsulfanyl)methanaminium"),
    ("COC[NH+](C)C.[Cl-]", "1-methoxy-N,N-dimethylmethanaminium chloride"),
    # already cited: the secondary and primary cations, the secondary amine
    ("COC[NH2+]C", "1-methoxy-N-methylmethanaminium"),
    ("COCNC", "1-methoxy-N-methylmethanamine"),
    ("NCc1ccccc1", "1-phenylmethanamine"),
])
def test_locant_one_is_cited_when_a_group_can_move_to_the_nitrogen(smiles, expected):
    assert _name(smiles) == expected


@pytest.mark.parametrize("smiles, expected", [
    # no hydrogen on the nitrogen and no group of it that could stand on the carbon: omits
    # (:36580 'cyano-N,N-dimethylmethanamine N-oxide (PIN)'). These rows were named in the brief of this
    # lane as missing '1-'; the Blue Book's own PIN of the same position structure has none.
    ("COCN(C)C", "methoxy-N,N-dimethylmethanamine"),
    ("COC[N+](C)(C)C", "methoxy-N,N,N-trimethylmethanaminium"),
])
def test_locant_one_stays_omitted_when_no_isomer_exists(smiles, expected):
    assert _name(smiles) == expected


def test_locant_one_stays_omitted_on_the_best_effort_quaternary_ring_row():
    """The PB final evals' pin_unverified row (best-effort tier only): a quaternary nitrogen."""
    best_effort = Orthonym(general_fallback=True, general_fallback_unverified=True,
                           allow_aromatic_general=True)
    assert best_effort.name("CC1=CC(CC1=O)C[N+](C)(C)C") == \
        "N,N,N-trimethyl(3-methyl-4-oxocyclopent-2-en-1-yl)methanaminium"


def test_the_hydron_scope_reads_the_nitrogen_with_one_hydrogen_more():
    from orthonym.assembly.locant_omission import (mononuclear_parent_locant_required,
                                                   suffix_nitrogen_gains_hydron)
    mol = Chem.MolFromSmiles("COCN(C)C")
    features = type("F", (), {})()
    features.mol = mol
    features.principal_chain = [2]
    features.principal_group_atoms = [(3,)]
    features.is_cyclic = False
    assert mononuclear_parent_locant_required(features) is False
    with suffix_nitrogen_gains_hydron():
        assert mononuclear_parent_locant_required(features) is True
    assert mononuclear_parent_locant_required(features) is False


def test_the_scope_does_not_leak_into_the_next_naming():
    """The neutral amine, its cation and the neutral amine again, in one process."""
    assert _name("COCN(C)C") == "methoxy-N,N-dimethylmethanamine"
    assert _name("COC[NH+](C)C") == "1-methoxy-N,N-dimethylmethanaminium"
    assert _name("COCN(C)C") == "methoxy-N,N-dimethylmethanamine"


@pytest.mark.parametrize("smiles, name, fails", [
    # a name that omits the locant although a group can move between the positions
    ("COC[NH+](C)C", "methoxy-N,N-dimethylmethanaminium", True),
    ("ClCNC", "chloro-N-methylmethanamine", True),
    ("c1ccccc1C=Nc1ccc(Cl)cc1", "N-(4-chlorophenyl)(phenyl)methanimine", True),
    ("CC1=CC=C(C=C1)CN2C=CC=C2C[NH+](CC3=CC=CC=C3)CC4=CC=CC=C4",
     "N,N-dibenzyl{1-[(4-methylphenyl)methyl]-1H-pyrrol-2-yl}methanaminium", True),
    # the names the rule accepts
    ("COC[NH+](C)C", "1-methoxy-N,N-dimethylmethanaminium", False),
    ("COCN(C)C", "methoxy-N,N-dimethylmethanamine", False),
    ("COC[N+](C)(C)C", "methoxy-N,N,N-trimethylmethanaminium", False),
    ("ClCNC", "1-chloro-N-methylmethanamine", False),
    ("C[N+](C)([O-])CC#N", "cyano-N,N-dimethylmethanamine N-oxide", False),
    ("O/N=C(/c1ccccc1)c1ccc(Cl)cc1", "(Z)-N-hydroxy(4-chlorophenyl)(phenyl)methanimine", False),
    ("Clc1ccc(C=Nc2ccc(Cl)cc2)cc1", "N,1-bis(4-chlorophenyl)methanimine", False),
    ("NCNN", "1-hydrazinylmethanamine", False),
    ("CN=Cc1ccccc1", "N-methyl(phenyl)methanimine", False),
])
def test_spelling_check_of_the_locant_on_a_one_carbon_amine_parent(smiles, name, fails):
    rules = [f.rule for f in check_pin_spelling(Chem.MolFromSmiles(smiles), name, strict=True)]
    assert ("P-14.3.4.4" in rules) is fails


def test_spelling_check_abstains_when_the_name_and_the_structure_do_not_agree_on_one_parent():
    # N-benzyl-N-methylmethanaminium: the parent is the methyl carbon, which holds no group
    mol = Chem.MolFromSmiles("C[NH+](C)Cc1ccccc1")
    assert check_pin_spelling(mol, "N-benzyl-N-methylmethanaminium", strict=True) == []
